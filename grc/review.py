"""Management review (ISO 42001 9.3).

One record per review: engagement/reviews/MR-YYYY-NN.yaml. The input pack (what management is
shown) is generated from the engagement record and frozen in MR-YYYY-NN-pack.md, with its SHA-256
in the record, so the minutes can be traced to exactly what was presented.

    python -m grc review new 2027-02-15          # schedule a review
    python -m grc review pack MR-2027-01         # (re)generate the input pack before the meeting

After the meeting, record notes against each input, decisions and actions (owner, due) in a PR.
Actions are mirrored to GitHub Issues and chased like gaps and findings.
"""
from __future__ import annotations

import collections
import datetime as dt
import hashlib
import re
from pathlib import Path

import yaml

from .model import Engagement, to_date

REVIEW_ID = re.compile(r"^MR-\d{4}-\d{2}$")
STANDARD_INPUTS = [
    {"id": "previous_actions", "title": "Status of actions from previous management reviews"},
    {"id": "context_changes", "title": "Changes in external and internal issues relevant to the AIMS"},
    {"id": "interested_parties", "title": "Changes in the needs and expectations of interested parties"},
    {"id": "performance", "title": "AIMS performance: nonconformities and corrective actions, monitoring and measurement, audit results"},
    {"id": "risks_and_impacts", "title": "AI risks and impact assessments, and the status of treatment"},
    {"id": "improvement", "title": "Opportunities for continual improvement"},
    {"id": "resources", "title": "Adequacy of resources"},
]
DEFAULT = {"review_every_days": 365, "warn_before_stage1_days": 60, "inputs": STANDARD_INPUTS}
HEADER = """# Management review - generated by `grc review new`; completed by the management system owner in PRs.
# Before the meeting: `grc review pack {id}` freezes the input pack. After it: set status: held,
# held_on, chair, attendees; write notes for EVERY input; record decisions and actions (owner, due).
# Close the review (status: closed) when the minutes are approved and every action is done or cancelled.
"""


def _doc_for(model: Engagement, requirement: str) -> str | None:
    """The library document that supports a requirement (e.g. 4.3 -> DOC-SCOPE / DOC-ISMS-SCOPE)."""
    from .documents import library
    return next((did for did, e in library(model).items() if requirement in (e.get("satisfies") or [])), None)


def method(model: Engagement) -> dict:
    cfg = {**DEFAULT, **(model.playbook.get("management_review") or {})}
    inputs = [i for i in cfg.get("inputs") or [] if isinstance(i, dict) and i.get("id")]
    cfg["inputs"] = inputs or STANDARD_INPUTS   # an empty list must never switch the notes check off
    return cfg


def safe_date(v) -> dt.date | None:
    try:
        return to_date(v)
    except (TypeError, ValueError, OverflowError):
        return None


def reviews(model: Engagement) -> dict[str, dict]:
    return {k: v for k, v in model.reviews.items() if isinstance(v, dict)}


def pack_path(model: Engagement, rid: str) -> Path:
    return model.engagement_dir / "reviews" / f"{rid}-pack.md"


def file_hash(path: Path) -> str | None:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None


def _dicts(xs) -> list[dict]:
    return [x for x in xs if isinstance(x, dict)] if isinstance(xs, list) else []


def actions(model: Engagement) -> list[dict]:
    """Every action from every review, with its review id."""
    out = []
    for rid, r in reviews(model).items():
        for a in _dicts(r.get("actions")):
            out.append({**a, "review": rid})
    return out


def _list(v) -> list:
    return v if isinstance(v, list) else []


def minutes_problems(model: Engagement, r: dict) -> list[str]:
    held = safe_date(r.get("held_on"))
    on = safe_date(r.get("minutes_approved_on"))
    if not str(r.get("minutes_approved_by") or "").strip() or not on:
        return ["minutes not approved (minutes_approved_by/on)"]
    if held and on < held:
        return ["minutes approved before the meeting was held"]
    if on > model.today:
        return ["minutes_approved_on is in the future"]
    return []


def problems(model: Engagement, rid: str, r: dict) -> list[str]:
    """What stops a review counting as held (and, for 'closed', as complete)."""
    p = []
    st = r.get("status")
    held = safe_date(r.get("held_on"))
    if not held:
        p.append("no held_on date")
    elif held > model.today:
        p.append("held_on is in the future")
    if not str(r.get("chair") or "").strip():
        p.append("no chair")
    if not [a for a in _list(r.get("attendees")) if str(a or "").strip()]:
        p.append("no attendees")
    notes = {str(i.get("id")): str(i.get("notes") or "").strip() for i in _dicts(r.get("inputs"))}
    missing = [i["id"] for i in method(model)["inputs"] if not notes.get(i["id"])]
    if missing:
        p.append(f"no notes for input(s): {', '.join(missing)}")
    if not [d for d in _dicts(r.get("decisions")) if str(d.get("decision") or "").strip()]:
        p.append("no decisions recorded (record 'no change needed' explicitly if that was the decision)")
    pk = r.get("pack") if isinstance(r.get("pack"), dict) else {}
    as_of = safe_date(pk.get("as_of"))
    actual = file_hash(pack_path(model, rid))
    if not pk.get("sha256") or not actual:
        p.append("no input pack (run `grc review pack` before the meeting)")
    elif pk.get("sha256") != actual:
        p.append("the input pack was changed after it was generated")
    elif held and as_of and as_of > held:
        p.append(f"the input pack is dated {as_of}, after the meeting")
    if st == "closed" or str(r.get("minutes_approved_by") or "").strip() or r.get("minutes_approved_on"):
        p += minutes_problems(model, r)
    if st == "closed" and any(a.get("status") == "open" for a in _dicts(r.get("actions"))):
        p.append("closed with open actions")
    return p


def is_sound(model: Engagement, rid: str) -> bool:
    r = model.reviews.get(rid)
    try:
        return isinstance(r, dict) and r.get("status") in ("held", "closed") and not problems(model, rid, r)
    except Exception:  # a malformed record is never sound, and never breaks anything else
        return False


def last_held(model: Engagement) -> tuple[str, dt.date] | None:
    held = [(rid, safe_date(r.get("held_on"))) for rid, r in reviews(model).items() if is_sound(model, rid)]
    held = [(rid, d) for rid, d in held if d]
    return max(held, key=lambda x: x[1]) if held else None


def evidence_entries(model: Engagement) -> dict[str, dict]:
    """A held review with complete minutes is citable as a record (e.g. for 9.3)."""
    out = {}
    days = int(method(model)["review_every_days"])
    for rid, r in model.reviews.items():
        r = r if isinstance(r, dict) else {}
        try:
            sound = is_sound(model, rid) and not minutes_problems(model, r)
            held = safe_date(r.get("held_on"))
        except Exception:
            sound, held = False, None
        out[rid] = {"id": rid, "title": f"Management review {rid}", "type": "record",
                    "location": f"{model.record_dir}/reviews/{rid}.yaml", "owner": str(r.get("chair") or ""),
                    "collected": held, "approved_by": str(r.get("minutes_approved_by") or "") if sound else "",
                    "approved_on": safe_date(r.get("minutes_approved_on")), "valid_for_days": days,
                    "source": "review", "result": None if sound else "fail",
                    "notes": f"status: {r.get('status', 'invalid')}"}
    return out


# ------------------------------------------------------------------ new
def write_new(engagement_dir: Path, on: dt.date, inputs: list[dict]) -> str:
    rdir = engagement_dir / "reviews"
    nums = [int(m.group(1)) for p in rdir.glob(f"MR-{on.year}-*.yaml") if (m := re.fullmatch(rf"MR-{on.year}-(\d+)", p.stem))]
    rid = f"MR-{on.year}-{max(nums or [0]) + 1:02d}"
    data = {
        "id": rid, "title": f"Management review {on:%B %Y}", "status": "planned", "planned_on": on.isoformat(),
        "held_on": None, "chair": "", "attendees": [], "pack": {"as_of": None, "sha256": None},
        "inputs": [{"id": i["id"], "notes": ""} for i in inputs],
        "decisions": [], "actions": [], "minutes_approved_by": "", "minutes_approved_on": None,
    }
    rdir.mkdir(parents=True, exist_ok=True)
    (rdir / f"{rid}.yaml").write_text(HEADER.format(id=rid) + yaml.safe_dump(data, sort_keys=False, allow_unicode=True),
                                      encoding="utf-8")
    return rid


def new(model: Engagement, on: dt.date) -> list[str]:
    rid = write_new(model.engagement_dir, on, method(model)["inputs"])
    return [f"{rid} planned for {on} (engagement/reviews/{rid}.yaml)"]


# ------------------------------------------------------------------ pack
def _table(headers, rows) -> str:
    cell = lambda v: str(v if v not in (None, "") else "—").replace("|", "/").replace("\n", " ")
    if not rows:
        return "_None._\n"
    return "\n".join(["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
                     + ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]) + "\n"


def pack_markdown(model: Engagement, rid: str) -> str:
    from . import documents, impact
    from .audit import audit_status
    from .rules import metrics, validate
    r = model.reviews[rid]
    m = metrics(model)
    findings = validate(model)
    prev = last_held(model)
    prev = prev if prev and prev[0] != rid else None
    since = prev[1] if prev else None
    configured = method(model)["inputs"]
    titles = {i["id"]: i.get("title") or i["id"] for i in configured}
    order = [i["id"] for i in configured]
    # a playbook input can reuse a built-in section under its own id: {id: control_performance, content: performance}
    content = {i["id"]: str(i.get("content") or i["id"]) for i in configured}
    head = L = [f"# {model.client} — management review input pack ({rid})\n",
         f"Prepared from the GRC record as of **{model.today}** for the review planned on {r.get('planned_on')}. "
         f"Previous management review: {f'{prev[0]} on {prev[1]}' if prev else 'none held yet'}. "
         "Figures are generated, not edited; the record behind each one is in the repository.\n"]

    sections: dict[str, list[str]] = {}

    def section(key):
        nonlocal L
        L = sections.setdefault(key, [])

    # 1. previous actions
    section("previous_actions")
    rows = []
    for a in actions(model):
        if a["review"] == rid:
            continue
        due = safe_date(a.get("due"))
        overdue = a.get("status") == "open" and due and due < model.today
        rows.append([f"{a['review']}/{a.get('id')}", a.get("action"), a.get("owner"), a.get("due"),
                     ("**overdue**" if overdue else a.get("status"))])
    L.append(_table(["Action", "What", "Owner", "Due", "Status"], rows))

    # 2. context changes
    section("context_changes")
    changed = []
    for did, d in documents.docs(model).items():
        for h in d["meta"].get("history") or []:
            when = safe_date(h.get("approved_on"))
            if when and (since is None or when > since):
                changed.append([did, d["meta"].get("title"), h.get("version"), when, h.get("approver")])
    ai = impact.required_systems(model)
    if model.uses_impact_assessments:
        L.append(f"- AI systems in scope: **{len(ai)}** ({', '.join(str(s.get('name')) for s in ai) or 'none'}).\n")
    scope_id = _doc_for(model, model.term("scope_ref"))
    scope = documents.docs(model).get(scope_id) if scope_id else None
    if scope_id:
        L.append(f"- Scope and context document ({scope_id}): **{scope['meta'].get('status') if scope else 'not started'}**"
                 f"{'' if not scope else ', version ' + str(scope['meta'].get('version'))}.\n")
    L.append(f"\nDocuments approved {'since ' + str(since) if since else 'to date'}:\n\n")
    L.append(_table(["Document", "Title", "Version", "Approved", "Approver"], changed))
    L.append("\n_For discussion: new laws or guidance, changes in technology, threats or suppliers, organisational changes._\n")

    # 3. interested parties
    section("interested_parties")
    concerns = [f for f in model.findings if isinstance(f, dict) and f.get("source") in ("incident", "other", "monitoring")]
    L.append(f"- Findings raised from incidents, monitoring or other sources: **{len(concerns)}**.\n")
    L.append("\n_For discussion: customer requirements and complaints, regulator expectations, concerns raised by staff "
             + ("or people affected by AI systems" if model.uses_impact_assessments else "or partners") + "._\n")

    # 4. performance
    section("performance")
    L.append(f"**Readiness:** {m['requirements_ready']} of {m['requirements_applicable']} applicable requirements ready; "
             f"{m['legs_verified_pct']}% of evidence-test legs verified. Open gaps: {m['gaps_open']} of {m['gaps_total']}. "
             f"Validation: {sum(f.severity == 'error' for f in findings)} errors, "
             f"{sum(f.severity == 'warning' for f in findings)} warnings.\n\n")
    L.append(_table(["Evidence test", "Verified", "Partial", "Claimed", "Not started"],
                    [[t["label"], *(m["legs"][t["key"]][k] for k in ("verified", "partial", "claimed", "not_started"))]
                     for t in model.playbook["evidence_test"]]))
    L.append("\n**Nonconformities and corrective actions**\n\n")
    grid = collections.Counter((f.get("grade"), f.get("status")) for f in model.findings if isinstance(f, dict))
    statuses = sorted({s for _, s in grid})
    L.append(_table(["Grade", *statuses], [[g, *(grid[(g, s)] for s in statuses)] for g in ("major", "minor", "ofi")
                                          if any(grid[(g, s)] for s in statuses)]))
    overdue = [f["id"] for f in model.findings if isinstance(f, dict) and f.get("status") not in ("closed", "accepted")
               and safe_date(f.get("due")) and safe_date(f.get("due")) < model.today]
    L.append(f"\nOverdue findings: {', '.join(overdue) or 'none'}.\n")
    L.append("\n**Monitoring and measurement**\n\n")
    L.append(f"- Expired evidence: {len(m['evidence_stale'])} · failing automated checks: {len(m.get('evidence_failing', []))}"
             + (f" ({', '.join(m.get('evidence_failing', []))})" if m.get("evidence_failing") else "") + ".\n")
    L.append("\n**Internal audit results**\n\n")
    arows = []
    for a in model.audits:
        if not isinstance(a, dict):
            continue
        try:
            s = audit_status(model, a["id"])
        except Exception:
            s = {}
        c = s.get("conclusions") or {}
        arows.append([a.get("id"), a.get("status"), s.get("workpapers", "—"), c.get("effective", 0),
                      c.get("not_effective", 0) + c.get("partially_effective", 0),
                      len([f for f in model.findings if isinstance(f, dict) and f.get("audit") == a.get("id")])])
    L.append(_table(["Audit", "Status", "Workpapers", "Effective", "Not effective", "Findings"], arows))
    obj_id = _doc_for(model, model.term("objectives_ref"))
    obj = documents.docs(model).get(obj_id) if obj_id else None
    if obj_id:
        L.append(f"\n**Objectives:** tracked in {obj_id} ({obj['meta'].get('status') if obj else 'not started'}).\n")

    # 5. risks and impacts
    section("risks_and_impacts")
    active = impact.active_by_system(model)
    rows = []
    for s in ai:
        ia = active.get(s["id"])
        if not ia:
            rows.append([s["id"], s.get("name"), "**missing**", "—", "—", "—", "—"])
            continue
        res = [impact.score(x.get("residual_likelihood"), x.get("residual_severity")) for x in _dicts(ia.get("impacts"))]
        res = [x for x in res if x is not None]
        accepted = sum(1 for x in _dicts(ia.get("impacts")) if isinstance(x.get("acceptance"), dict) and x["acceptance"].get("accepted_by"))
        top = max(res) if res else None
        nr = impact.next_review(model, ia)
        rows.append([s["id"], s.get("name"), f"{ia['id']} {ia.get('status')}" + (" ✅" if impact.is_effective(model, ia) else ""),
                     f"{top} {impact.band(model, top)}" if top else "—", accepted, len(ia.get("conditions") or []), nr or "—"])
    if model.uses_impact_assessments:
        L.append(_table(["System", "Name", "Assessment", "Highest residual", "Accepted risks", "Conditions", "Next review"], rows))
    risk_doc = _doc_for(model, model.term("risk_ref"))
    if risk_doc:
        rd = documents.docs(model).get(risk_doc)
        L.append(f"\nRisk method ({risk_doc}): {rd['meta'].get('status') if rd else 'not started'}. "
                 "Record the latest risk assessment results and the treatment plan status in the notes.\n")
    sev = collections.Counter(g.get("severity") or "unrated" for g in model.gaps if g.get("status") in ("open", "in_progress"))
    L.append(f"\nOpen gaps by severity: {', '.join(f'{k} {v}' for k, v in sorted(sev.items())) or 'none'}.\n")

    # 6. improvement
    section("improvement")
    ofis = [[f["id"], f.get("requirement"), f.get("description")] for f in model.findings
            if isinstance(f, dict) and f.get("grade") == "ofi" and f.get("status") not in ("closed", "accepted")]
    L.append("Open opportunities for improvement:\n\n" + _table(["OFI", "Requirement", "Description"], ofis))
    due_docs = []
    for did in documents.library(model):
        d = model.documents.get(did)
        if not d or not isinstance(d.get("meta"), dict):
            due_docs.append([did, "not started"])
        elif not documents.is_effective(model, did):
            due_docs.append([did, str(d["meta"].get("status"))])
    L.append(f"\nPolicies and procedures not yet approved and current: **{len(due_docs)}** of {len(documents.library(model))}"
             + (f" ({', '.join(d[0] for d in due_docs)})" if due_docs else "") + ".\n")

    # 7. resources
    section("resources")
    # Consulting hours are the engagement team's economics, not the AIMS's resources: not in the pack.
    no_owner = [r["id"] for r in model.requirements if model.is_applicable(r["id"])
                and not str(model.controls.get(r["id"], {}).get("owner") or "").strip()]
    L.append(f"- Applicable requirements without an accountable owner: **{len(no_owner)}**.\n"
             f"\n_For discussion: people, skills, tools and budget the {model.system_abbrev} needs for the next period._\n")
    # 8. incidents and 9. suppliers: used by playbooks that ask for them (SOC 2)
    section("incidents")
    inc = [[f["id"], f.get("grade"), f.get("requirement"), f.get("status"), f.get("description")] for f in model.findings
           if isinstance(f, dict) and f.get("source") == "incident"]
    L.append("Findings raised from security incidents:\n\n" + _table(["Finding", "Grade", "Requirement", "Status", "Description"], inc))
    L.append("\n_For discussion: incidents since the last review, how they were handled, and lessons learned._\n")
    section("suppliers")
    sup = [[i.get("id"), i.get("name"), i.get("owner")] for i in model.inventory
           if isinstance(i, dict) and i.get("kind") in ("supplier_service", "infrastructure") and i.get("in_scope") is not False]
    L.append("Suppliers and subservice organizations in scope:\n\n" + _table(["ID", "Name", "Owner"], sup))
    L.append("\n_For discussion: their latest SOC reports or assessments, exceptions noted, and complementary controls._\n")

    out = head
    for n, key in enumerate(order, start=1):
        out += [f"\n## {n}. {titles[key]}\n\n"] + (sections.get(content[key]) or
                                                    ["_No generated data for this input; record the discussion in the review._\n"])
    out.append("\n---\n_Record notes against each numbered input, decisions and actions in the review record._\n")
    return "".join(out)


def _plain(v):
    """YAML-loaded dates back to ISO strings, so the record round-trips cleanly."""
    if isinstance(v, dict):
        return {k: _plain(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_plain(x) for x in v]
    if isinstance(v, dt.date):
        return v.isoformat()
    return v


def pack(model: Engagement, rid: str, force: bool = False) -> list[str]:
    r = model.reviews.get(rid)
    if not isinstance(r, dict):
        raise ValueError(f"{rid}: no such review (engagement/reviews/{rid}.yaml)")
    if r.get("status") in ("held", "closed") and not force:
        raise ValueError(f"{rid} is {r.get('status')}: its input pack is the record of what was presented and is frozen")
    path = pack_path(model, rid)
    path.write_text(pack_markdown(model, rid), encoding="utf-8")
    h = file_hash(path)
    rpath = model.review_files[rid]
    data = dict(r)
    data["pack"] = {"as_of": model.today.isoformat(), "sha256": h}
    rpath.write_text(HEADER.format(id=rid) + yaml.safe_dump(_plain(data), sort_keys=False, allow_unicode=True), encoding="utf-8")
    return [f"{rid} input pack written to engagement/reviews/{rid}-pack.md (as of {model.today}, sha256 {h[:12]})"]
