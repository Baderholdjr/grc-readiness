// Seshat consultant workspace - Cloudflare Worker.
//
// Consultants sign in with GitHub (through the Seshat Workspace GitHub App: OAuth with state and PKCE). Their
// short-lived user token, which GitHub limits to the repositories both they and the App can reach, is kept only
// in an encrypted, HttpOnly, Secure, SameSite=Strict session cookie. Every change is a pull request opened with
// that token, so it is authored by the consultant, and needs the same review and checks as any other.
//
//   GET  /auth/login           start GitHub sign-in
//   GET  /auth/callback        finish it (checks state, PKCE; the login must be on CONSULTANTS)
//   POST /auth/logout          end the session
//   GET  /api/me               who is signed in
//   GET  /api/engagements      client repositories the App and the consultant can both reach
//   GET  /api/engagement?repo= one record: requirements, gaps, owners, evidence ids (read from main)
//   POST /api/change           propose a change to one requirement: becomes a pull request
//
// What can change: a requirement's implementation statement and owner, and one evidence check's status
// (not_started, claimed or partial - never verified), the evidence it cites and its note. Verified stays the
// reviewer's own edit in the pull request.
//
// Settings (wrangler.toml [vars], generated by `grc workspace`): GITHUB_CLIENT_ID, CONSULTANTS (GitHub logins,
// comma-separated), BASE_BRANCH. Secrets: GITHUB_CLIENT_SECRET, SESSION_KEY (32+ random characters).
import { json, plain, withHeaders } from "./access.js";
import { EditError, WORKSPACE_STATUSES, setLegField, setRequirementField } from "./yamledit.js";
import { CORE_SCHEMA, load as yamlLoad } from "./js-yaml.mjs";
import { checkEdit } from "./recordcheck.js";

const SESSION_COOKIE = "__Host-ws_session";
const OAUTH_COOKIE = "__Host-ws_oauth";
const MAX_BODY = 16 * 1024;
const MAX_TEXT = 4000;
const SESSION_HOURS = 8;
const REPO_RE = /^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+$/;
const LEGS = ["documented", "implemented", "evidenced", "tested"];

export default {
  async fetch(request, env) {
    try {
      return await handle(request, env);
    } catch (err) {
      console.error("unhandled", err && err.stack ? err.stack : String(err));
      return json({ error: "Something went wrong on our side. Try again in a minute." }, 500);
    }
  },
};

export function configured(env) {
  return /^[A-Za-z0-9.]{8,40}$/.test(String(env.GITHUB_CLIENT_ID || "")) && !!env.GITHUB_CLIENT_SECRET &&
    String(env.SESSION_KEY || "").length >= 32 && consultants(env).length > 0;
}

function consultants(env) {
  return String(env.CONSULTANTS || "").split(",").map((s) => s.trim().toLowerCase()).filter((s) => /^[a-z0-9-]{1,39}$/.test(s));
}

async function handle(request, env) {
  const url = new URL(request.url);
  if (!configured(env)) {
    return url.pathname.startsWith("/api/") ? json({ error: "The workspace isn't set up yet." }, 503) : plain("The workspace isn't set up yet.", 503);
  }
  if (url.pathname === "/auth/login" && request.method === "GET") return login(url, env);
  if (url.pathname === "/auth/callback" && request.method === "GET") return callback(request, url, env);
  if (url.pathname === "/auth/logout" && request.method === "POST") {
    if (!sameOrigin(request, url)) return json({ error: "Sign out from the workspace itself." }, 403);
    const s = await unseal(env, "session", cookies(request)[SESSION_COOKIE]);
    if (s && typeof s.token === "string") await revoke(env, s.token);   // the token stops working at GitHub too
    return withCookie(json({ ok: true }), clearCookie(SESSION_COOKIE));
  }
  const session = await readSession(request, env);
  if (url.pathname.startsWith("/api/")) {
    if (!session) return json({ error: "Sign in again.", signin: true }, 401);
    return api(request, env, url, session);
  }
  if (request.method !== "GET" && request.method !== "HEAD") return plain("Method not allowed.", 405);
  const res = await env.ASSETS.fetch(request);
  const out = withHeaders(new Response(res.body, res));
  out.headers.set("Cache-Control", "no-store");
  return out;
}

// ------------------------------------------------------------------ crypto: sealed cookies (AES-GCM)
const enc = new TextEncoder();
const dec = new TextDecoder();

function b64u(bytes) {
  let s = "";
  for (const b of new Uint8Array(bytes)) s += String.fromCharCode(b);
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function unb64u(s) {
  const t = String(s).replace(/-/g, "+").replace(/_/g, "/");
  const bin = atob(t + "===".slice((t.length + 3) % 4));
  return Uint8Array.from(bin, (c) => c.charCodeAt(0));
}

async function key(env, purpose) {
  const raw = await crypto.subtle.digest("SHA-256", enc.encode(`${purpose}:${env.SESSION_KEY}`));
  return crypto.subtle.importKey("raw", raw, "AES-GCM", false, ["encrypt", "decrypt"]);
}

export async function seal(env, purpose, obj) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, await key(env, purpose), enc.encode(JSON.stringify(obj)));
  return `${b64u(iv)}.${b64u(ct)}`;
}

export async function unseal(env, purpose, value) {
  try {
    const [iv, ct] = String(value || "").split(".");
    const pt = await crypto.subtle.decrypt({ name: "AES-GCM", iv: unb64u(iv) }, await key(env, purpose), unb64u(ct));
    const obj = JSON.parse(dec.decode(pt));
    return obj && typeof obj.exp === "number" && obj.exp > Date.now() ? obj : null;
  } catch {
    return null;
  }
}

function cookies(request) {
  const out = {};
  for (const part of String(request.headers.get("Cookie") || "").split(";")) {
    const i = part.indexOf("=");
    if (i > 0) out[part.slice(0, i).trim()] = part.slice(i + 1).trim();
  }
  return out;
}

function setCookie(name, value, maxAge, sameSite = "Strict") {
  return `${name}=${value}; Path=/; HttpOnly; Secure; SameSite=${sameSite}; Max-Age=${maxAge}`;
}

function clearCookie(name) {
  return `${name}=; Path=/; HttpOnly; Secure; SameSite=Strict; Max-Age=0`;
}

function withCookie(res, ...values) {
  for (const v of values) res.headers.append("Set-Cookie", v);
  return res;
}

async function readSession(request, env) {
  const s = await unseal(env, "session", cookies(request)[SESSION_COOKIE]);
  if (!s || typeof s.token !== "string" || !consultants(env).includes(String(s.login || "").toLowerCase())) return null;
  return s;
}

function sameOrigin(request, url) {
  const site = request.headers.get("Sec-Fetch-Site");
  return request.headers.get("Origin") === url.origin && (!site || site === "same-origin");
}

// ------------------------------------------------------------------ sign-in (GitHub App OAuth, state + PKCE)
async function login(url, env) {
  const state = b64u(crypto.getRandomValues(new Uint8Array(32)));
  const verifier = b64u(crypto.getRandomValues(new Uint8Array(32)));
  const challenge = b64u(await crypto.subtle.digest("SHA-256", enc.encode(verifier)));
  const sealed = await seal(env, "oauth", { state, verifier, exp: Date.now() + 10 * 60_000 });
  const to = new URL("https://github.com/login/oauth/authorize");
  to.searchParams.set("client_id", env.GITHUB_CLIENT_ID);
  to.searchParams.set("redirect_uri", `${url.origin}/auth/callback`);
  to.searchParams.set("state", state);
  to.searchParams.set("code_challenge", challenge);
  to.searchParams.set("code_challenge_method", "S256");
  to.searchParams.set("allow_signup", "false");
  // Lax: this cookie must come back on GitHub's redirect to /auth/callback (a top-level GET from github.com)
  return withCookie(new Response(null, { status: 302, headers: { Location: to.href, "Cache-Control": "no-store" } }),
    setCookie(OAUTH_COOKIE, sealed, 600, "Lax"));
}

function timingSafeEqual(a, b) {
  const x = enc.encode(String(a)), y = enc.encode(String(b));
  if (x.length !== y.length) return false;
  let d = 0;
  for (let i = 0; i < x.length; i++) d |= x[i] ^ y[i];
  return d === 0;
}

function page(title, body, status = 200) {
  // a tiny same-origin page: continuing from here is a same-site navigation, so the Strict cookie is sent
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">` +
    `<title>${title}</title><link rel="stylesheet" href="/app.css"></head><body><main class="narrow"><h1>${title}</h1>${body}</main></body></html>`;
  return withHeaders(new Response(html, { status, headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store" } }));
}

async function revoke(env, token) {
  try {
    const res = await fetch(`https://api.github.com/applications/${encodeURIComponent(env.GITHUB_CLIENT_ID)}/token`, {
      method: "DELETE",
      headers: { Authorization: `Basic ${btoa(`${env.GITHUB_CLIENT_ID}:${env.GITHUB_CLIENT_SECRET}`)}`, Accept: "application/vnd.github+json",
        "Content-Type": "application/json", "User-Agent": "seshat-workspace" },
      body: JSON.stringify({ access_token: token }),
    });
    if (!res.ok && res.status !== 404) console.error("revoke", res.status);
  } catch (err) {
    console.error("revoke", String(err));
  }
}

async function callback(request, url, env) {
  const fail = (why) => withCookie(page("Sign-in didn't complete", `<p>${why}</p><p><a class="btn" href="/auth/login">Try again</a></p>`, 400),
    clearCookie(OAUTH_COOKIE));
  const pending = await unseal(env, "oauth", cookies(request)[OAUTH_COOKIE]);
  const state = url.searchParams.get("state") || "";
  const code = url.searchParams.get("code") || "";
  if (!pending || !state || !timingSafeEqual(state, pending.state)) return fail("The sign-in link expired or was opened in another browser.");
  if (!/^[A-Za-z0-9_-]{8,80}$/.test(code)) return fail("GitHub didn't send a sign-in code.");
  const res = await fetch("https://github.com/login/oauth/access_token", {
    method: "POST",
    headers: { Accept: "application/json", "Content-Type": "application/json", "User-Agent": "seshat-workspace" },
    body: JSON.stringify({ client_id: env.GITHUB_CLIENT_ID, client_secret: env.GITHUB_CLIENT_SECRET, code,
      redirect_uri: `${url.origin}/auth/callback`, code_verifier: pending.verifier }),
  });
  const tok = res.ok ? await res.json().catch(() => ({})) : {};
  if (!tok.access_token || typeof tok.access_token !== "string") {
    console.error("token exchange", res.status, tok.error || "");
    return fail("GitHub didn't accept the sign-in.");
  }
  if (!(Number(tok.expires_in) > 0)) {
    // a token that never expires means the App's "Expire user authorization tokens" setting is off
    await revoke(env, tok.access_token);
    return fail("The GitHub App must have <b>Expire user authorization tokens</b> turned on.");
  }
  const me = await gh(tok.access_token, "GET", "/user");
  const user = me.ok ? await me.json() : null;
  const login = String((user && user.login) || "").toLowerCase();
  if (!login || !consultants(env).includes(login)) {
    console.log(JSON.stringify({ event: "signin_refused", login }));
    return fail("This GitHub account isn't on the workspace's list of consultants.");
  }
  const hours = Math.min(SESSION_HOURS, Number(tok.expires_in || 0) / 3600 || SESSION_HOURS);
  const session = await seal(env, "session", { token: tok.access_token, login, exp: Date.now() + hours * 3600_000 });
  console.log(JSON.stringify({ event: "signin", login }));
  return withCookie(page("Signed in", `<p>Signed in as <b>${login}</b>.</p><p><a class="btn" href="/">Open the workspace</a></p>`),
    setCookie(SESSION_COOKIE, session, Math.floor(hours * 3600)), clearCookie(OAUTH_COOKIE));
}

// ------------------------------------------------------------------ GitHub, as the consultant
async function gh(token, method, path, body) {
  return fetch(`https://api.github.com${path}`, {
    method,
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "seshat-workspace", ...(body ? { "Content-Type": "application/json" } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
}

// whether this consultant may push to one repository (GitHub also refuses any write the App isn't installed for)
async function canPush(token, repo) {
  const r = await gh(token, "GET", `/repos/${repo}`);
  if (!r.ok) return false;
  const d = await r.json();
  return !!(d && d.permissions && d.permissions.push) && String(d.full_name || "").toLowerCase() === repo.toLowerCase();
}

// the client repositories this consultant may use: where the App is installed and they can push
export async function reachableRepos(token) {
  const out = [];
  const installs = [];
  for (let page = 1; page <= 10; page++) {
    const inst = await gh(token, "GET", `/user/installations?per_page=100&page=${page}`);
    if (!inst.ok) return null;
    const batch = (await inst.json()).installations || [];
    installs.push(...batch);
    if (batch.length < 100) break;
  }
  for (const i of installs) {
    for (let page = 1; page <= 10; page++) {
      const r = await gh(token, "GET", `/user/installations/${encodeURIComponent(i.id)}/repositories?per_page=100&page=${page}`);
      if (!r.ok) return null;
      const batch = (await r.json()).repositories || [];
      for (const repo of batch) if (repo.permissions && repo.permissions.push && REPO_RE.test(repo.full_name)) out.push(repo.full_name);
      if (batch.length < 100) break;
    }
  }
  return [...new Set(out)].sort();
}

function parseYaml(text) {
  try {
    return yamlLoad(String(text), { schema: CORE_SCHEMA, json: false }) || {};
  } catch {
    return null;
  }
}

// every record file in one GraphQL call (the controls folder can hold hundreds of files)
async function readRecord(token, repo, base) {
  const [owner, name] = repo.split("/");
  const query = `query($o:String!,$n:String!,$c:String!,$e:String!,$g:String!,$w:String!,$v:String!){repository(owner:$o,name:$n){
    controls:object(expression:$c){... on Tree{entries{name object{... on Blob{text byteSize}}}}}
    engagement:object(expression:$e){... on Blob{text}} gaps:object(expression:$g){... on Blob{text}}
    owners:object(expression:$w){... on Blob{text}} evidence:object(expression:$v){... on Blob{text}}
    ref(qualifiedName:"refs/heads/${base}"){target{oid}}}}`;
  const res = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json", "User-Agent": "seshat-workspace" },
    body: JSON.stringify({ query, variables: { o: owner, n: name, c: `${base}:engagement/controls`, e: `${base}:engagement/engagement.yaml`,
      g: `${base}:engagement/gaps.yaml`, w: `${base}:engagement/owners.yaml`, v: `${base}:engagement/evidence/index.yaml` } }),
  });
  const body = res.ok ? await res.json().catch(() => null) : null;
  return body && body.data && body.data.repository ? body.data.repository : null;
}

// text from the record: only plain values (an object or a list of aliases is never turned into text)
function str(v, max = MAX_TEXT) {
  return ["string", "number", "boolean"].includes(typeof v) ? String(v).slice(0, max) : "";
}

export function recordView(repo, r) {
  const eng = parseYaml(r.engagement && r.engagement.text) || {};
  const reqs = [];
  for (const e of (r.controls && r.controls.entries) || []) {
    if (!/^[A-Za-z0-9._()&,+ -]+\.yaml$/.test(e.name) || !e.object || typeof e.object.text !== "string") continue;
    const text = e.object.text;
    const d = parseYaml(text);
    if (!d || typeof d !== "object") continue;
    const head = /^#\s*(\S+)\s+(.+)$/m.exec(text.split("\n")[0] || "");
    const test = d.test && typeof d.test === "object" ? d.test : {};
    reqs.push({
      id: str(d.id, 120), title: head ? str(head[2], 200) : "", path: `engagement/controls/${e.name}`,
      owner: str(d.owner, 200), implementation: str(d.implementation), applicable: d.applicable !== false,
      legs: Object.fromEntries(LEGS.map((l) => {
        const x = test[l] && typeof test[l] === "object" ? test[l] : {};
        return [l, { status: str(x.status, 20) || "not_started", note: str(x.note, 1000),
          evidence: Array.isArray(x.evidence) ? x.evidence.map((v) => str(v, 60)) : [] }];
      })),
    });
  }
  reqs.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
  const seen = new Set();
  const dupes = new Set(reqs.filter((x) => (seen.has(x.id) ? true : (seen.add(x.id), false))).map((x) => x.id));
  const gaps = ((parseYaml(r.gaps && r.gaps.text) || {}).gaps || []).filter((g) => g && typeof g === "object").map((g) => ({
    id: str(g.id, 40), area: str(g.area, 200), severity: str(g.severity, 20), status: str(g.status, 20), due: str(g.due, 20),
    owner: str(g.owner, 200), requirements: Array.isArray(g.requirements) ? g.requirements.map((x) => str(x, 120)) : [] }));
  const owners = ((parseYaml(r.owners && r.owners.text) || {}).owners || []).filter((o) => o && o.role).map((o) => str(o.role, 200));
  const evidence = ((parseYaml(r.evidence && r.evidence.text) || {}).evidence || []).filter((x) => x && x.id)
    .map((x) => ({ id: str(x.id, 40), title: str(x.title, 200), type: str(x.type, 20) }));
  // a requirement written in two files is shown, but can't be changed here: which file is meant is unclear
  for (const x of reqs) if (dupes.has(x.id)) x.duplicate = true;
  return { repo, client: str(eng.client, 200), framework: str(eng.framework, 40), base: r.ref && r.ref.target ? r.ref.target.oid : null,
    requirements: reqs, gaps, owners, evidence };
}

async function readJson(request) {
  if (!/^application\/json\b/i.test(request.headers.get("Content-Type") || "")) return null;
  if (Number(request.headers.get("Content-Length") || 0) > MAX_BODY) return null;
  const raw = await request.text();
  if (raw.length > MAX_BODY) return null;
  try {
    const b = JSON.parse(raw);
    return b && typeof b === "object" && !Array.isArray(b) ? b : null;
  } catch {
    return null;
  }
}

function cleanText(s, max) {
  let t = String(s == null ? "" : s).normalize("NFC").replace(/\r\n?/g, "\n").replace(/[\u2028\u2029\u0085]/g, "\n");
  t = t.replace(/[^\t\n\x20-\x7E\xA0-\uD7FF\uE000-\uFFFD\u{10000}-\u{10FFFF}]/gu, "").replace(/[\u202A-\u202E\u2066-\u2069]/g, "");
  return t.trim().slice(0, max);
}

// what the consultant asked for, checked; the file comes from the record, never from the request
export function parseChange(b, view) {
  const req = view.requirements.find((r) => r.id === String(b.requirement || ""));
  if (!req) return { error: "That requirement isn't in the record." };
  if (req.duplicate) return { error: `${req.id} is written in more than one file. Fix that in GitHub first.` };
  const field = String(b.field || "");
  if (field === "implementation") {
    const v = cleanText(b.value, MAX_TEXT + 1);
    if (!v || v.length > MAX_TEXT) return { error: "Write the implementation statement (up to 4,000 characters)." };
    return { req, field, value: v, summary: `implementation statement for ${req.id}` };
  }
  if (field === "owner") {
    const v = String(b.value || "");
    if (!view.owners.includes(v)) return { error: "Choose an owner from the record's owner roles." };
    return { req, field, value: v, summary: `owner of ${req.id}: ${v}` };
  }
  if (!["status", "note", "evidence"].includes(field)) return { error: "That can't be changed from the workspace." };
  const leg = String(b.leg || "");
  if (!LEGS.includes(leg)) return { error: "Choose an evidence check." };
  if (req.legs[leg].status === "verified") {
    return { error: "This check is verified. Its status, evidence and note change only in a reviewer's edit in GitHub." };
  }
  if (field === "status") {
    const v = String(b.value || "");
    if (!WORKSPACE_STATUSES.includes(v)) return { error: "From the workspace a check can be not started, claimed or partial. Verified is set by the reviewer in the pull request." };
    return { req, field, leg, value: v, summary: `${leg} check of ${req.id}: ${v.replace("_", " ")}` };
  }
  if (field === "note") {
    const v = cleanText(b.value, 1001);
    if (v.length > 1000) return { error: "Keep the note under 1,000 characters." };
    return { req, field, leg, value: v, summary: `note on the ${leg} check of ${req.id}` };
  }
  if (field === "evidence") {
    const ids = Array.isArray(b.value) ? [...new Set(b.value.map((x) => String(x)))] : null;
    const known = new Set(view.evidence.map((x) => x.id));
    if (!ids || ids.length > 30 || !ids.every((x) => known.has(x))) return { error: "Cite evidence by its id from the evidence index." };
    return { req, field, leg, value: ids, summary: `evidence cited by the ${leg} check of ${req.id}` };
  }
  return { error: "That can't be changed from the workspace." };
}

async function api(request, env, url, session) {
  const base = /^[A-Za-z0-9._/-]{1,100}$/.test(String(env.BASE_BRANCH || "main")) ? String(env.BASE_BRANCH || "main") : "main";
  if (url.pathname === "/api/me" && request.method === "GET") return json({ login: session.login });
  if (url.pathname === "/api/engagements" && request.method === "GET") {
    const repos = await reachableRepos(session.token);
    if (!repos) return json({ error: "GitHub didn't list your repositories. Sign in again.", signin: true }, 401);
    return json({ repos });
  }
  if (url.pathname === "/api/engagement" && request.method === "GET") {
    const repo = String(url.searchParams.get("repo") || "");
    if (!REPO_RE.test(repo)) return json({ error: "Unknown engagement." }, 400);
    if (!(await canPush(session.token, repo))) return json({ error: "You don't have access to that engagement." }, 403);
    const r = await readRecord(session.token, repo, base);
    if (!r || !r.engagement) return json({ error: "That repository has no engagement record." }, 404);
    return json(recordView(repo, r));
  }
  if (url.pathname === "/api/change") {
    if (request.method !== "POST") return json({ error: "Use POST." }, 405);
    if (!sameOrigin(request, url)) return json({ error: "Send changes from the workspace itself." }, 403);
    const b = await readJson(request);
    if (!b) return json({ error: "Expected JSON." }, 400);
    const repo = String(b.repo || "");
    if (!REPO_RE.test(repo)) return json({ error: "Unknown engagement." }, 400);
    if (!(await canPush(session.token, repo))) return json({ error: "You don't have access to that engagement." }, 403);
    const r = await readRecord(session.token, repo, base);
    if (!r || !r.engagement || !r.ref) return json({ error: "That repository has no engagement record." }, 404);
    const view = recordView(repo, r);
    const c = parseChange(b, view);
    if (c.error) return json({ error: c.error }, 400);
    return change(session, repo, base, view, c);
  }
  return json({ error: "Not found." }, 404);
}

function b64utf8(s) {
  const bytes = enc.encode(s);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

function md(s) {
  return String(s).replace(/[\\`*_{}\[\]()#+!<>|~@:]/g, (c) => "\\" + c).replace(/\n/g, " ");
}

async function change(session, repo, base, view, c) {
  const t = session.token;
  const enc2 = (p) => p.split("/").map(encodeURIComponent).join("/");
  // the commit the record was read and checked at, so the edit applies to exactly what was checked
  const sha = view.base;
  if (!/^[0-9a-f]{40}$/.test(String(sha))) return json({ error: "Couldn't read the main branch." }, 502);
  let res = await gh(t, "GET", `/repos/${repo}/contents/${enc2(c.req.path)}?ref=${sha}`);
  if (!res.ok) return json({ error: `GitHub refused (${res.status}) reading ${c.req.path}.` }, 502);
  const file = await res.json();
  const before = dec.decode(Uint8Array.from(atob(String(file.content || "").replace(/\n/g, "")), (ch) => ch.charCodeAt(0)));
  let after;
  try {
    after = c.leg ? setLegField(before, c.leg, c.field, c.value) : setRequirementField(before, c.field, c.value);
  } catch (err) {
    if (err instanceof EditError) return json({ error: `${c.req.path} isn't laid out the way the workspace can change it (${err.message}). Edit it in GitHub.` }, 409);
    throw err;
  }
  if (after === before) return json({ error: "That's what the record already says." }, 409);
  const allowed = c.leg ? [`test.${c.leg}.${c.field}`, ...(c.field === "evidence" ? [`test.${c.leg}.evidence.`] : [])] : [c.field];
  const why = checkEdit(before, after, allowed);
  if (why) {
    console.error("edit refused by the record check", why);
    return json({ error: `${c.req.path} isn't laid out the way the workspace can change it (${why}). Edit it in GitHub.` }, 409);
  }
  const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
  const branch = `workspace/${session.login}/${stamp}-${b64u(crypto.getRandomValues(new Uint8Array(3)))}`;
  res = await gh(t, "POST", `/repos/${repo}/git/refs`, { ref: `refs/heads/${branch}`, sha });
  if (!res.ok) return json({ error: `GitHub refused (${res.status}) creating a branch.` }, 502);
  const cleanup = () => gh(t, "DELETE", `/repos/${repo}/git/refs/heads/${branch}`).catch(() => {});
  res = await gh(t, "PUT", `/repos/${repo}/contents/${enc2(c.req.path)}`, {
    message: `Workspace: ${c.summary}`.slice(0, 200), content: b64utf8(after), sha: file.sha, branch });
  if (!res.ok) { await cleanup(); return json({ error: `GitHub refused (${res.status}) writing the change.` }, 502); }
  res = await gh(t, "POST", `/repos/${repo}/pulls`, {
    title: `Workspace: ${c.summary}`.slice(0, 200), head: branch, base,
    body: [`Proposed from the Seshat workspace by @${session.login}.`, "", `- Change: ${md(c.summary)}`, `- File: \`${c.req.path}\``, "",
      "**Files changed** shows exactly what would change. Review it like any other change; merging applies it.",
      "Nothing here marks a check verified: that is the reviewer's own edit."].join("\n") });
  if (!res.ok) { await cleanup(); return json({ error: `GitHub refused (${res.status}) opening the pull request.` }, 502); }
  const pr = await res.json();
  console.log(JSON.stringify({ event: "change", login: session.login, repo, pr: pr.number }));
  return json({ ok: true, number: pr.number, url: String(pr.html_url || "") });
}
