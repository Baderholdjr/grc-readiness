// GRC read-only rooms - Cloudflare Worker for the auditor room and the executive dashboard.
//
// One Worker per room per client (ROOM = "auditor" or "executive"), each behind its own Cloudflare Access
// application. Every request, pages included (run_worker_first), must carry a valid Access login, checked here
// as well as at the edge (access.js). Nothing here writes anywhere: the pages and files are built from the merged
// record by `grc rooms`, and GitHub stays the system of record.
//
//   GET /            the room's page (static files in public/)
//   GET /api/me      who is signed in, for the stamp on every page
//   GET /files/...   auditor room only: the auditor package's files, downloaded (never rendered here)
//
// The auditor room also checks, on every request:
//   - the signed-in email is on AUDITORS (the named auditors from engagement.yaml), and
//   - today is within ROOM_OPENS .. ROOM_CLOSES (inclusive, UTC), so the room shuts on its own.
// Both are checked in addition to the Access policy, so a policy left too wide still lets no one else in.
//
// Settings (wrangler.toml [vars], generated by `grc rooms`): ROOM, ACCESS_TEAM, ACCESS_AUD,
// ALLOWED_EMAIL_DOMAINS, and for the auditor room AUDITORS, ROOM_OPENS, ROOM_CLOSES.
import { authenticate, json, plain, withHeaders } from "./access.js";

export { _resetCertCache } from "./access.js";

const DAY = /^\d{4}-\d{2}-\d{2}$/;

export default {
  async fetch(request, env) {
    try {
      return await handle(request, env);
    } catch (err) {
      console.error("unhandled", err && err.stack ? err.stack : String(err));
      return json({ error: "Something went wrong on our side. Try again in a minute." }, 500);
    }
  },
};

export function roomCheck(env, email, now = new Date()) {
  const room = String(env.ROOM || "");
  if (room === "executive") return { ok: true, room };
  if (room !== "auditor") return { ok: false, status: 503, reason: "This room isn't set up yet." };
  const opens = String(env.ROOM_OPENS || ""), closes = String(env.ROOM_CLOSES || "");
  const auditors = String(env.AUDITORS || "").split(",").map((a) => a.trim().toLowerCase()).filter(Boolean);
  if (!DAY.test(opens) || !DAY.test(closes) || !auditors.length) {
    return { ok: false, status: 503, reason: "This room isn't set up yet: its dates or auditors are missing." };
  }
  if (!auditors.includes(email)) {
    return { ok: false, status: 403, reason: "This email address isn't on the list of auditors for this engagement." };
  }
  const today = now.toISOString().slice(0, 10);
  if (today < opens) return { ok: false, status: 403, reason: `This room opens on ${opens}.` };
  if (today > closes) return { ok: false, status: 403, reason: `This room closed on ${closes}. Ask the engagement team if you need it again.` };
  return { ok: true, room, opens, closes };
}

async function handle(request, env) {
  const url = new URL(request.url);
  const isApi = url.pathname.startsWith("/api/");
  if (request.method !== "GET" && request.method !== "HEAD") {
    return isApi ? json({ error: "This room is read only." }, 405) : plain("This room is read only.", 405);
  }
  const who = await authenticate(request, env);
  if (!who.ok) return isApi ? json({ error: who.reason }, who.status) : plain(who.reason, who.status);
  const room = roomCheck(env, who.email);
  if (!room.ok) return isApi ? json({ error: room.reason }, room.status) : plain(room.reason, room.status);
  if (isApi) {
    if (url.pathname === "/api/me") {
      console.log(JSON.stringify({ event: "view", room: room.room, email: who.email }));
      return json({ email: who.email, room: room.room, opens: room.opens || null, closes: room.closes || null,
        at: new Date().toISOString() });
    }
    return json({ error: "Not found." }, 404);
  }
  const isFile = url.pathname.startsWith("/files/");
  if (isFile && room.room !== "auditor") return plain("Not found.", 404);
  if (isFile) console.log(JSON.stringify({ event: "download", room: room.room, email: who.email, path: url.pathname }));
  const res = await env.ASSETS.fetch(request);
  const out = withHeaders(new Response(res.body, res));
  if (isFile && res.ok) {
    // never rendered in the room's origin: a report can't run script here, whatever it contains
    out.headers.set("Content-Disposition", "attachment");
    out.headers.set("Content-Type", "application/octet-stream");
  }
  out.headers.set("Cache-Control", "private, no-store");
  return out;
}
