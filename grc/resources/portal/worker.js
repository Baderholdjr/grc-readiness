const MAX_BODY = 16 * 1024;
const MAX_ANSWER = 4000;
const MAX_LINKS = 5;
const MAX_OPEN_TOTAL = 40;       // answers waiting for review, whole site
const MAX_OPEN_PER_PERSON = 15;  // ... per signed-in person
const BURST = 5;                 // answers per person per minute (per Worker instance; see docs)
const PENDING_TTL = 20_000;      // ms the open-answer list is reused between page loads


export default {
  async fetch(request, env) {
    try {
      return await handle(request, env);
    } catch (err) {
      console.error("unhandled", err && err.stack ? err.stack : String(err));
      return json({ error: "Something went wrong on our side. Try again in a minute." }, 500);
    }
  },
};

async function handle(request, env) {
  const url = new URL(request.url);
  const isApi = url.pathname.startsWith("/api/");
  const who = await authenticate(request, env);
  if (!who.ok) return deny(who, isApi);
  if (isApi) return api(request, env, url, who.email);
  if (request.method !== "GET" && request.method !== "HEAD") return plain("Method not allowed.", 405);
  const res = await env.ASSETS.fetch(request);
  return withHeaders(new Response(res.body, res));
}

function deny(who, isApi) {
  return isApi ? json({ error: who.reason }, who.status) : plain(who.reason, who.status);
}

// ------------------------------------------------------------------ API
async function api(request, env, url, email) {
  const path = url.pathname;
  if (path === "/api/me" && request.method === "GET") return json({ email });
  if (path === "/api/pending" && request.method === "GET") {
    const cfg = repoConfig(env);
    if (!cfg.ok) return json({ pending: [], connected: false });
    const open = await openSubmissions(env, cfg);
    if (!open) return json({ error: "Couldn't check for answers waiting for review." }, 502);
    return json({ connected: true, pending: open.map(({ key, id, at }) => ({ key, id, at })) });
  }
  if (path === "/api/submit") {
    if (request.method !== "POST") return json({ error: "Use POST." }, 405);
    return submit(request, env, url, email);
  }
  if (path === "/api/edit") {
    if (request.method !== "POST") return json({ error: "Use POST." }, 405);
    return edit(request, env, url, email);
  }
  return json({ error: "Not found." }, 404);
}

function repoConfig(env) {
  const repo = String(env.GITHUB_REPO || "");
  const base = String(env.BASE_BRANCH || "main");
  if (!/^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+$/.test(repo) || !env.GITHUB_TOKEN ||
      !/^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*$/.test(base) || base.includes("..")) {
    return { ok: false };
  }
  return { ok: true, repo, base };
}

async function gh(env, method, path, body) {
  return fetch(`https://api.github.com${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${env.GITHUB_TOKEN}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "grc-client-site",
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
}

const BRANCH_RE = /^portal\/([0-9a-f]{12})\/(SUB-\d{8}-[0-9a-f]{6})$/;

let pendingCache = { repo: "", at: 0, list: null };
const inFlight = new Set();          // people with an answer being sent right now
const recent = new Map();            // email -> times of recent answers

export function _resetState() {
  pendingCache = { repo: "", at: 0, list: null };
  inFlight.clear();
  recent.clear();
}

async function openSubmissions(env, cfg, fresh = false) {
  if (!fresh && pendingCache.repo === cfg.repo && pendingCache.list && Date.now() - pendingCache.at < PENDING_TTL) {
    return pendingCache.list;
  }
  const pulls = [];
  for (let page = 1; page <= 3; page++) {          // up to 300 open pull requests
    const res = await gh(env, "GET", `/repos/${cfg.repo}/pulls?state=open&per_page=100&page=${page}`);
    if (!res.ok) {
      console.error("list pulls", res.status);
      return null;
    }
    const batch = await res.json();
    pulls.push(...batch);
    if (batch.length < 100) break;
  }
  const out = [];
  for (const pr of pulls) {
    const m = BRANCH_RE.exec((pr.head && pr.head.ref) || "");
    if (!m || !pr.head.repo || pr.head.repo.full_name !== cfg.repo) continue; // only branches the site made, in this repo
    const by = /Submitted by: `([^`]+)`/.exec(pr.body || "");
    out.push({ key: m[1], id: m[2], at: String(pr.created_at || "").slice(0, 10), by: by ? by[1] : "" });
  }
  pendingCache = { repo: cfg.repo, at: Date.now(), list: out };
  return out;
}

function shownEmail(email) {
  return email.replace(/`/g, "'");   // as written in the pull request body
}

async function readCapped(request, max) {
  if (!request.body) return "";
  const reader = request.body.getReader();
  const chunks = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.byteLength;
    if (size > max) {
      await reader.cancel().catch(() => {});
      return null;
    }
    chunks.push(value);
  }
  const all = new Uint8Array(size);
  let at = 0;
  for (const c of chunks) {
    all.set(c, at);
    at += c.byteLength;
  }
  return new TextDecoder().decode(all);
}

// Text a person typed: keep what YAML can carry, normalise line breaks, drop control characters.
export function cleanText(s, max) {
  let t = String(s == null ? "" : s).normalize("NFC").replace(/\r\n?/g, "\n").replace(/[\u2028\u2029\u0085]/g, "\n");
  t = t.replace(/[^\t\n\x20-\x7E\xA0-\uD7FF\uE000-\uFFFD\u{10000}-\u{10FFFF}]/gu, "");
  t = t.replace(/[\u202A-\u202E\u2066-\u2069]/g, ""); // no bidirectional overrides
  return t.trim().slice(0, max);
}

export function cleanLink(s) {
  const raw = String(s == null ? "" : s).trim();
  if (!raw) return null;
  if (raw.length > 500 || /[\s\x00-\x1F\x7F]/.test(raw)) return undefined;
  let u;
  try {
    u = new URL(raw);
  } catch {
    return undefined;
  }
  if (u.protocol !== "https:" || u.username || u.password) return undefined;
  const href = u.href;
  return href.length <= 500 && !/\s/.test(href) ? href : undefined;
}

function q(s) {
  return JSON.stringify(String(s)); // a JSON string is a valid YAML double-quoted scalar
}

export function submissionYaml(sub) {
  return [
    "# Client submission, sent from the client site. Review it like any other change:",
    "# set status to accepted, needs_more (with a note the client will see) or withdrawn,",
    "# and add reviewed_by / reviewed_on. This file does not change any control, gap or",
    "# evidence status by itself - file evidence in evidence/index.yaml as usual.",
    `id: ${q(sub.id)}`,
    "request:",
    `  key: ${q(sub.request.key)}`,
    `  kind: ${q(sub.request.kind)}`,
    `  ref: ${q(sub.request.ref)}`,
    `  title: ${q(sub.request.title)}`,
    `  framework: ${q(sub.request.framework)}`,
    `submitted_by: ${q(sub.submitted_by)}`,
    `submitted_at: ${q(sub.submitted_at)}`,
    `answer: ${q(sub.answer)}`,
    `links: [${sub.links.map(q).join(", ")}]`,
    "no_sensitive_data: true",
    "status: received",
    "",
  ].join("\n");
}

function md(s) {
  return String(s).replace(/[\\`*_{}\[\]()#+!<>|~@:]/g, (c) => "\\" + c).replace(/\n/g, " ");
}

function b64utf8(s) {
  const bytes = new TextEncoder().encode(s);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

function newId(now) {
  const d = now.toISOString().slice(0, 10).replace(/-/g, "");
  const r = new Uint8Array(3);
  crypto.getRandomValues(r);
  return `SUB-${d}-${[...r].map((b) => b.toString(16).padStart(2, "0")).join("")}`;
}

async function findRequest(env, url, key) {
  const res = await env.ASSETS.fetch(new Request(new URL("/portal.json", url.origin)));
  if (!res.ok) return null;
  const data = await res.json();
  for (const fw of data.frameworks || []) {
    for (const r of fw.requests || []) if (r.key === key && r.answerable) return r;
  }
  return null;
}

async function submit(request, env, url, email) {
  // same-site JSON only: a form on another site can't send this
  const origin = request.headers.get("Origin");
  const site = request.headers.get("Sec-Fetch-Site");
  if (origin !== url.origin || (site && site !== "same-origin")) return json({ error: "Send answers from the site itself." }, 403);
  if (!/^application\/json\b/i.test(request.headers.get("Content-Type") || "")) return json({ error: "Expected JSON." }, 415);
  const declared = Number(request.headers.get("Content-Length") || 0);
  if (declared > MAX_BODY) return json({ error: "That answer is too long. Keep it under 4,000 characters." }, 413);
  const raw = await readCapped(request, MAX_BODY);
  if (raw === null) return json({ error: "That answer is too long. Keep it under 4,000 characters." }, 413);
  let body;
  try {
    body = JSON.parse(raw);
  } catch {
    return json({ error: "Expected JSON." }, 400);
  }
  if (!body || typeof body !== "object") return json({ error: "Expected JSON." }, 400);
  const key = String(body.key || "");
  if (!/^[0-9a-f]{12}$/.test(key)) return json({ error: "Unknown request." }, 400);
  if (body.no_sensitive_data !== true) {
    return json({ error: "Confirm that your answer contains no patient or personal data." }, 400);
  }
  if (typeof body.answer !== "string" && body.answer != null) return json({ error: "The answer must be text." }, 400);
  if (String(body.answer || "").length > MAX_ANSWER * 2) return json({ error: "That answer is too long. Keep it under 4,000 characters." }, 413);
  const answer = cleanText(body.answer, MAX_ANSWER + 1);
  if (answer.length > MAX_ANSWER) return json({ error: "That answer is too long. Keep it under 4,000 characters." }, 413);
  const rawLinks = Array.isArray(body.links) ? body.links : [];
  if (rawLinks.length > MAX_LINKS) return json({ error: `Add at most ${MAX_LINKS} links.` }, 400);
  const links = [];
  for (const l of rawLinks) {
    const c = cleanLink(l);
    if (c === undefined) return json({ error: "Each link must be a full https:// address, like https://drive.example.com/file." }, 400);
    if (c) links.push(c);
  }
  if (!answer && !links.length) return json({ error: "Write an answer or add a link before sending." }, 400);

  const cfg = repoConfig(env);
  if (!cfg.ok) return json({ error: "Answers can't be sent yet: the site isn't connected to the engagement record." }, 503);
  const req = await findRequest(env, url, key);
  if (!req) return json({ error: "This request is no longer open. Reload the page to see the current list." }, 409);

  // One answer at a time per person, a few per minute, and caps on what waits for review.
  // These hold per Worker instance; production should add Cloudflare rate limiting (docs/CLIENT-SITE.md).
  const now0 = Date.now();
  const times = (recent.get(email) || []).filter((t) => now0 - t < 60_000);
  if (inFlight.has(email) || times.length >= BURST) {
    return json({ error: "You've sent several answers in the last minute. Wait a moment and try again." }, 429);
  }
  inFlight.add(email);
  recent.set(email, [...times, now0]);
  try {
    const open = await openSubmissions(env, cfg, true);
    if (!open) return json({ error: "We couldn't send your answer. Nothing was saved. Try again in a minute." }, 502);
    if (open.length >= MAX_OPEN_TOTAL || open.filter((o) => o.by === shownEmail(email)).length >= MAX_OPEN_PER_PERSON) {
      return json({ error: "Many answers are already waiting for review. Try again once the team has caught up." }, 429);
    }
    return await createSubmission(env, cfg, key, req, email, answer, links, open);
  } finally {
    inFlight.delete(email);
  }
}

async function createSubmission(env, cfg, key, req, email, answer, links, open) {

  const now = new Date();
  const id = newId(now);
  const sub = {
    id,
    request: {
      key,
      kind: cleanText(req.kind, 80),
      ref: cleanText(req.ref, 120),
      title: cleanText(req.title, 300),
      framework: cleanText(req.framework, 40),
    },
    submitted_by: email,
    submitted_at: now.toISOString().replace(/\.\d{3}Z$/, "Z"),
    answer,
    links,
  };
  const branch = `portal/${key}/${id}`;
  const file = `engagement/submissions/${id}.yaml`;

  let res = await gh(env, "GET", `/repos/${cfg.repo}/git/ref/heads/${cfg.base}`);
  if (!res.ok) return ghFail("read base", res);
  const sha = (await res.json()).object.sha;
  res = await gh(env, "POST", `/repos/${cfg.repo}/git/refs`, { ref: `refs/heads/${branch}`, sha });
  if (!res.ok) return ghFail("create branch", res);
  const cleanup = () => gh(env, "DELETE", `/repos/${cfg.repo}/git/refs/heads/${branch}`).catch(() => {});
  res = await gh(env, "PUT", `/repos/${cfg.repo}/contents/${file}`, {
    message: `Client submission ${id}: ${sub.request.kind} ${sub.request.ref}`.slice(0, 200),
    content: b64utf8(submissionYaml(sub)),
    branch,
  });
  if (!res.ok) {
    await cleanup();
    return ghFail("write file", res);
  }
  const prBody = [
    "**Client submission** sent from the client site.",
    "",
    `- Request: ${md(sub.request.kind)} ${md(sub.request.ref)} ${md(sub.request.title)}`,
    `- Submitted by: \`${shownEmail(email)}\` (verified by Cloudflare Access)`,
    `- File: \`${file}\``,
    "",
    "Before merging, read the answer and open any links under **Files changed**. Then set `status` to",
    "`accepted`, `needs_more` (with a `note` the client will see) or `withdrawn`, and add `reviewed_by`.",
    "Merging records the answer; it does not change any control, gap or evidence status.",
  ].join("\n");
  res = await gh(env, "POST", `/repos/${cfg.repo}/pulls`, {
    title: `Client submission: ${sub.request.kind} ${sub.request.ref}`.slice(0, 200),
    head: branch,
    base: cfg.base,
    body: prBody,
  });
  if (!res.ok) {
    await cleanup();
    return ghFail("open pull request", res);
  }
  const pr = await res.json();
  await gh(env, "POST", `/repos/${cfg.repo}/issues/${pr.number}/labels`, { labels: ["client-submission"] }).catch(() => {});
  open.push({ key, id, at: sub.submitted_at.slice(0, 10), by: shownEmail(email) });
  pendingCache = { repo: cfg.repo, at: Date.now(), list: open };
  return json({ ok: true, id, at: sub.submitted_at.slice(0, 10) });
}

// A short reference the client can pass on: which step failed and GitHub's status code.
// 401 = token invalid/expired; 403/404 = token can't reach the repository or lacks a permission.
const STEP_CODES = { "read base": "R", "read file": "G", "create branch": "B", "write file": "F", "open pull request": "P" };

function ghFail(step, res) {
  console.error(`github ${step}: ${res.status}`);
  const ref = `${STEP_CODES[step] || "G"}${res.status}`;
  return json({ error: `We couldn't send your answer to the engagement team. Nothing was saved. Try again, or contact your engagement lead (reference ${ref}).`, ref }, 502);
}


// ------------------------------------------------------------------ proposed changes (POST /api/edit)
const EVIDENCE_TYPES = new Set(["document", "record", "config", "log", "screenshot"]);   // not test types: a reviewer tests
const MAX_TITLE = 200;
const EMAIL_RE = /^[^@\s"'<>`]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$/;
const PATH_RE = /^engagement\/[A-Za-z0-9._()&,+ \/-]+\.yaml$/;

async function portalData(env, url) {
  const res = await env.ASSETS.fetch(new Request(new URL("/portal.json", url.origin)));
  return res.ok ? res.json() : null;
}

// the request (requirement) or owner role a key names, and what may be changed on it, from portal.json
export function findTarget(data, kind, key) {
  const kinds = new Set(Array.isArray(data && data.edits) ? data.edits : []);
  if (!kinds.has(kind)) return null;
  if (kind === "owner_email") {
    const o = data.owners;
    const r = o && Array.isArray(o.roles) ? o.roles.find((x) => x.key === key) : null;
    return r && PATH_RE.test(o.path) && !o.path.includes("..") ? { path: o.path, role: r.role, ref: r.role, title: `Owner: ${r.role}` } : null;
  }
  for (const fw of data.frameworks || []) {
    // only a requirement's own change key (from the Progress page), never a request's answer key
    const rows = (fw.areas || []).flatMap((a) => (a.requirements || []).map((x) => ({ ...x, ref: x.id, framework: fw.key })));
    for (const r of rows) {
      if (r.key !== key || !r.edit) continue;
      if (kind === "implementation" && r.edit.path && PATH_RE.test(r.edit.path) && !r.edit.path.includes("..")) {
        return { path: r.edit.path, ref: r.ref, title: r.title, framework: r.framework };
      }
      if (kind === "evidence" && r.edit.evidence) {
        return { path: "engagement/evidence/index.yaml", ref: r.ref, title: r.title, framework: r.framework };
      }
    }
  }
  return null;
}

async function readJson(request, url) {
  const origin = request.headers.get("Origin");
  const site = request.headers.get("Sec-Fetch-Site");
  if (origin !== url.origin || (site && site !== "same-origin")) return { error: json({ error: "Send changes from the site itself." }, 403) };
  if (!/^application\/json\b/i.test(request.headers.get("Content-Type") || "")) return { error: json({ error: "Expected JSON." }, 415) };
  if (Number(request.headers.get("Content-Length") || 0) > MAX_BODY) return { error: json({ error: "That's too long." }, 413) };
  const raw = await readCapped(request, MAX_BODY);
  if (raw === null) return { error: json({ error: "That's too long." }, 413) };
  try {
    const body = JSON.parse(raw);
    return body && typeof body === "object" && !Array.isArray(body) ? { body } : { error: json({ error: "Expected JSON." }, 400) };
  } catch {
    return { error: json({ error: "Expected JSON." }, 400) };
  }
}

// what the person asked for, checked and cleaned; never a path
export function parseEdit(body) {
  const kind = String(body.kind || "");
  const key = String(body.key || "");
  if (!["implementation", "owner_email", "evidence"].includes(kind)) return { error: "Unknown kind of change." };
  if (!/^[0-9a-f]{12}$/.test(key)) return { error: "Unknown request." };
  if (body.no_sensitive_data !== true) return { error: "Confirm that your change contains no patient or personal data." };
  if (kind === "implementation") {
    if (typeof body.value !== "string") return { error: "Write how this is done." };
    if (body.value.length > MAX_ANSWER * 2) return { error: "Keep it under 4,000 characters." };
    const value = cleanText(body.value, MAX_ANSWER + 1);
    if (!value) return { error: "Write how this is done." };
    if (value.length > MAX_ANSWER) return { error: "Keep it under 4,000 characters." };
    return { kind, key, value };
  }
  if (kind === "owner_email") {
    const value = cleanText(body.value, 255).toLowerCase();
    if (!EMAIL_RE.test(value) || value.length > 254) return { error: "Enter an email address, like name@example.com." };
    return { kind, key, value };
  }
  const title = cleanText(body.title, MAX_TITLE + 1).replace(/\n/g, " ");
  if (!title) return { error: "Give the evidence a short title." };
  if (title.length > MAX_TITLE) return { error: "Keep the title under 200 characters." };
  const type = String(body.type || "");
  if (!EVIDENCE_TYPES.has(type)) return { error: "Choose what kind of evidence it is." };
  const link = cleanLink(body.link);
  if (!link) return { error: "The link must be a full https:// address, like https://drive.example.com/file." };
  return { kind, key, title, type, link };
}

async function edit(request, env, url, email) {
  const { body, error } = await readJson(request, url);
  if (error) return error;
  const e = parseEdit(body);
  if (e.error) return json({ error: e.error }, 400);
  const cfg = repoConfig(env);
  if (!cfg.ok) return json({ error: "Changes can't be sent yet: the site isn't connected to the engagement record." }, 503);
  const data = await portalData(env, url);
  const target = data && findTarget(data, e.kind, e.key);
  if (!target) return json({ error: "This can't be changed from the site. Reload the page to see the current list." }, 409);

  const now0 = Date.now();
  const times = (recent.get(email) || []).filter((t) => now0 - t < 60_000);
  if (inFlight.has(email) || times.length >= BURST) {
    return json({ error: "You've sent several changes in the last minute. Wait a moment and try again." }, 429);
  }
  inFlight.add(email);
  recent.set(email, [...times, now0]);
  try {
    const open = await openSubmissions(env, cfg, true);
    if (!open) return json({ error: "We couldn't send your change. Nothing was saved. Try again in a minute." }, 502);
    if (open.length >= MAX_OPEN_TOTAL || open.filter((o) => o.by === shownEmail(email)).length >= MAX_OPEN_PER_PERSON) {
      return json({ error: "Many changes are already waiting for review. Try again once the team has caught up." }, 429);
    }
    return await createChange(env, cfg, e, target, email, open);
  } finally {
    inFlight.delete(email);
  }
}

function fromB64(s) {
  const bin = atob(String(s).replace(/\n/g, ""));
  return new TextDecoder().decode(Uint8Array.from(bin, (c) => c.charCodeAt(0)));
}

async function createChange(env, cfg, e, target, email, open) {
  const now = new Date();
  const id = newId(now);
  const at = now.toISOString().replace(/\.\d{3}Z$/, "Z");
  const branch = `portal/${e.key}/${id}`;
  const enc = (p) => p.split("/").map(encodeURIComponent).join("/");

  let res = await gh(env, "GET", `/repos/${cfg.repo}/git/ref/heads/${cfg.base}`);
  if (!res.ok) return ghFail("read base", res);
  const sha = (await res.json()).object.sha;
  res = await gh(env, "GET", `/repos/${cfg.repo}/contents/${enc(target.path)}?ref=${sha}`);
  if (!res.ok) return ghFail("read file", res);
  const file = await res.json();
  if (file.type !== "file" || typeof file.content !== "string") return json({ error: "That record file couldn't be read." }, 409);
  const before = fromB64(file.content);

  let after, summary, value, targetName;
  try {
    if (e.kind === "implementation") {
      after = setImplementation(before, e.value);
      summary = `implementation statement for ${target.ref}`;
      value = e.value;
      targetName = target.ref;
    } else if (e.kind === "owner_email") {
      after = setOwnerEmail(before, target.role, e.value);
      summary = `email for the ${target.role} owner`;
      value = e.value;
      targetName = target.role;
    } else {
      const added = addEvidence(before, {
        title: e.title, type: e.type, location: e.link, collected: at.slice(0, 10),
        notes: `Added from the client site by ${email} on ${at.slice(0, 10)}; not reviewed yet.`,
        requirements: [target.ref],
      });
      after = added.text;
      summary = `evidence link ${added.id} for ${target.ref}`;
      value = e.link;
      targetName = added.id;
    }
  } catch (err) {
    if (err instanceof EditError) {
      console.error("edit refused", err.message);
      return json({ error: "That record file isn't laid out the way the site can change it. Ask your engagement team to make this change." }, 409);
    }
    throw err;
  }
  if (after === before) return json({ error: "That's what the record already says." }, 409);
  // second check: the file, parsed, differs only where this change is meant to (and nothing became verified)
  const doc = parsed(before) || {};
  let allowed;
  if (e.kind === "implementation") allowed = ["implementation"];
  else if (e.kind === "owner_email") {
    const i = (Array.isArray(doc.owners) ? doc.owners : []).findIndex((o) => o && o.role === target.role);
    allowed = [`owners.${i}.email`];
  } else {
    const n = Array.isArray(doc.evidence) ? doc.evidence.length : 0;
    allowed = [`evidence.${n}`, `evidence.${n}.`, ...(n ? [] : ["evidence"])];   // the new item only
  }
  const why = checkEdit(before, after, allowed);
  if (why) {
    console.error("edit refused by the record check", why);
    return json({ error: "That record file isn't laid out the way the site can change it. Ask your engagement team to make this change." }, 409);
  }

  const sub = submissionYaml({
    id,
    request: { key: e.key, kind: "Change", ref: cleanText(target.ref, 120), title: cleanText(target.title, 300),
      framework: cleanText(target.framework || "", 40) },
    submitted_by: email, submitted_at: at,
    answer: `Proposed ${summary}.`, links: e.kind === "evidence" ? [e.link] : [],
  }).replace("status: received\n", () =>   // a function: "$&" or "$`" in the client's text must stay literal
    `change:\n  kind: ${q(e.kind)}\n  file: ${q(target.path)}\n  target: ${q(cleanText(targetName, 200))}\n  value: ${q(value)}\nstatus: received\n`);
  const trailer = `\n\nSubmitted-by: ${email.replace(/[\r\n]/g, "")}`;

  res = await gh(env, "POST", `/repos/${cfg.repo}/git/refs`, { ref: `refs/heads/${branch}`, sha });
  if (!res.ok) return ghFail("create branch", res);
  const cleanup = () => gh(env, "DELETE", `/repos/${cfg.repo}/git/refs/heads/${branch}`).catch(() => {});
  res = await gh(env, "PUT", `/repos/${cfg.repo}/contents/${enc(target.path)}`, {
    message: `Client change ${id}: ${summary}`.slice(0, 200) + trailer, content: b64utf8(after), sha: file.sha, branch,
  });
  if (!res.ok) { await cleanup(); return ghFail("write file", res); }
  res = await gh(env, "PUT", `/repos/${cfg.repo}/contents/engagement/submissions/${id}.yaml`, {
    message: `Client change ${id}: who proposed it`.slice(0, 200) + trailer, content: b64utf8(sub), branch,
  });
  if (!res.ok) { await cleanup(); return ghFail("write file", res); }
  const prBody = [
    "**Client change** proposed from the client site.",
    "",
    `- Change: ${md(summary)}`,
    `- Submitted by: \`${shownEmail(email)}\` (verified by Cloudflare Access)`,
    `- Record file changed: \`${target.path}\``,
    `- Who and when: \`engagement/submissions/${id}.yaml\``,
    "",
    "**Files changed** shows exactly what would change in the record. Merging applies it; closing discards it.",
    "It changes no status: no requirement, gap or evidence becomes verified because of it.",
    "Before merging, set the submission's `status` to `accepted` and add `reviewed_by`.",
  ].join("\n");
  res = await gh(env, "POST", `/repos/${cfg.repo}/pulls`, {
    title: `Client change: ${summary}`.slice(0, 200), head: branch, base: cfg.base, body: prBody,
  });
  if (!res.ok) { await cleanup(); return ghFail("open pull request", res); }
  const pr = await res.json();
  await gh(env, "POST", `/repos/${cfg.repo}/issues/${pr.number}/labels`, { labels: ["client-submission"] }).catch(() => {});
  open.push({ key: e.key, id, at: at.slice(0, 10), by: shownEmail(email) });
  pendingCache = { repo: cfg.repo, at: Date.now(), list: open };
  return json({ ok: true, id, at: at.slice(0, 10) });
}
