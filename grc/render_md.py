"""Markdown/CSV/JSON reports: control matrix, SoA, gap register, evidence index, status."""
from __future__ import annotations

import csv
import json
from pathlib import Path

from .model import LEGS, Engagement
from .rules import Finding, leg_effective, metrics, requirement_state

ICON = {"verified": "✅", "partial": "🟡", "claimed": "❔", "not_started": "⬜"}
GEN = "<!-- Generated by `python -m grc build`. Do not edit; change the YAML and let CI rebuild. -->\n\n"


def _esc(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def _write_csv(path: Path, headers, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(headers)
        w.writerows(rows)


def _evidence_for(c: dict) -> list[str]:
    ids = []
    for k in LEGS:
        for e in c.get("test", {}).get(k, {}).get("evidence", []) or []:
            if e not in ids:
                ids.append(e)
    return ids


# -------------------------------------------------------------- control matrix
def control_matrix(model: Engagement, out: Path):
    headers = ["ID", "Requirement", "Type", "Owner", "Documented", "Implemented", "Evidenced", "Tested", "State", "Gaps", "Evidence"]
    rows, csv_rows = [], []
    for r in model.requirements:
        c = model.controls.get(r["id"], {})
        eff = {k: leg_effective(model, c.get("test", {}).get(k, {})) for k in LEGS}
        state = requirement_state(model, r["id"])
        kind = "Clause" if r["kind"] == "clause" else "Annex A"
        ev = _evidence_for(c)
        gaps = c.get("gaps", []) or []
        if state == "Excluded":
            legs_md = ["—"] * 4
        else:
            legs_md = [ICON[eff[k]] for k in LEGS]
        rows.append([r["id"], r["title"], kind, c.get("owner", ""), *legs_md, state, ", ".join(gaps), ", ".join(ev)])
        csv_rows.append([r["id"], r["title"], kind, c.get("owner", ""), *[eff[k] for k in LEGS], state, ";".join(gaps), ";".join(ev)])
    m = metrics(model)
    md = [f"# {model.client} — {model.catalog['framework']['short_name']} control matrix\n", GEN,
          f"As of **{m['as_of']}**: {m['requirements_ready']}/{m['requirements_applicable']} applicable requirements ready · "
          f"{m['legs_verified_pct']}% of evidence-test legs verified · {m['gaps_open']} open gaps.\n\n",
          "Legend: ✅ verified · 🟡 partial · ❔ client claim, not yet evidenced · ⬜ not started\n\n"]
    for grp in model.catalog["groups"]:
        grows = [row for row, r in zip(rows, model.requirements) if r["group"] == grp["id"]]
        if grows:
            prefix = "Clause " if not grp["id"].startswith("A.") else ""
            md.append(f"## {prefix}{grp['id']} {grp['title']}\n\n")
            md.append(_table(headers, grows) + "\n")
    (out / "control-matrix.md").write_text("".join(md), encoding="utf-8")
    _write_csv(out / "control-matrix.csv", headers, csv_rows)


# -------------------------------------------------- statement of applicability
def soa(model: Engagement, out: Path):
    headers = ["Control", "Title", "Applicable", "Justification", "Implementation", "State", "Owner"]
    rows = []
    for r in model.requirements:
        if r["kind"] != "control":
            continue
        c = model.controls.get(r["id"], {})
        rows.append([r["id"], r["title"], "Yes" if c.get("applicable", True) else "No",
                     c.get("justification", ""), c.get("implementation", ""), requirement_state(model, r["id"]), c.get("owner", "")])
    md = [f"# {model.client} — Statement of Applicability (draft)\n", GEN,
          "Annex A controls with inclusion/exclusion justification and implementation status. "
          "Approval of the SoA is recorded by merging the PR that changes it.\n\n", _table(headers, rows)]
    (out / "soa.md").write_text("".join(md), encoding="utf-8")
    _write_csv(out / "soa.csv", headers, rows)


# ---------------------------------------------------------------- gap register
def gap_register(model: Engagement, out: Path):
    headers = ["ID", "Area", "Finding", "Requirements", "Owner", "Due", "Phase", "Severity", "Status", "Issue"]
    rows = [[g["id"], g["area"], model.fmt(g["finding"]), ", ".join(g.get("requirements", [])), g.get("owner", ""),
             g.get("due", ""), g.get("phase", ""), g.get("severity", ""), g["status"],
             f"#{g['issue']}" if g.get("issue") else ""] for g in model.gaps]
    md = [f"# {model.client} — gap register\n", GEN, _table(headers, rows)]
    (out / "gap-register.md").write_text("".join(md), encoding="utf-8")
    _write_csv(out / "gap-register.csv", headers, rows)


# -------------------------------------------------------------- evidence index
def evidence_index(model: Engagement, out: Path):
    supports: dict[str, list[str]] = {}
    for cid, c in model.controls.items():
        for k in LEGS:
            for e in c.get("test", {}).get(k, {}).get("evidence", []) or []:
                supports.setdefault(e, [])
                tag = f"{cid}·{k[0].upper()}"
                if tag not in supports[e]:
                    supports[e].append(tag)
    headers = ["ID", "Title", "Type", "Location", "Collected", "Expires", "Current", "Approved by", "Supports"]
    rows = []
    for e in model.evidence:
        exp = model.evidence_expiry(e)
        rows.append([e["id"], e["title"], e["type"], e["location"], e["collected"], exp.isoformat() if exp else "",
                     ("**FAILING**" if model.evidence_is_failing(e) else "**EXPIRED**" if model.evidence_is_expired(e) else "yes")
                     + (f" ({e['collector']})" if e.get("collector") else ""), e.get("approved_by", ""),
                     ", ".join(supports.get(e["id"], [])) or "(unused)"])
    md = [f"# {model.client} — evidence index\n", GEN,
          "Each row is a pointer to an artifact held in the client's systems. "
          "`Supports` lists requirement·leg (D/I/E/T) that cite it, so an auditor can trace requirement → evidence.\n\n",
          _table(headers, rows)]
    (out / "evidence-index.md").write_text("".join(md), encoding="utf-8")
    _write_csv(out / "evidence-index.csv", headers, rows)


# --------------------------------------------------------------------- status
def status(model: Engagement, findings: list[Finding], out: Path) -> str:
    m = metrics(model)
    m["findings"] = {s: sum(1 for f in findings if f.severity == s) for s in ("error", "warning", "info")}
    (out / "status.json").write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8")
    return summary_markdown(model, findings, m)


def summary_markdown(model: Engagement, findings: list[Finding], m: dict | None = None) -> str:
    m = m or metrics(model)
    lines = [f"## {model.client} — {m['framework']} readiness ({m['as_of']})\n",
             f"- **Ready:** {m['requirements_ready']} / {m['requirements_applicable']} applicable requirements",
             f"- **Evidence-test legs verified:** {m['legs_verified_pct']}%",
             f"- **Open gaps:** {m['gaps_open']} of {m['gaps_total']}",
             (f"- **Open nonconformities:** {m['nc_open_major']} major · {m['nc_open_minor']} minor"
              if m.get("findings_total") else ""),
             f"- **Expired evidence:** {len(m['evidence_stale'])} · **Failing collector checks:** {len(m.get('evidence_failing', []))}",
             f"- **Budget:** {m['hours_used']:g} / {m['hours_total']:g} hours\n" if m.get("hours_total") else "",
             "| Test | ✅ Verified | 🟡 Partial | ❔ Claimed | ⬜ Not started |", "|---|---|---|---|---|"]
    for t in model.playbook["evidence_test"]:
        L = m["legs"][t["key"]]
        lines.append(f"| {t['label']} | {L['verified']} | {L['partial']} | {L['claimed']} | {L['not_started']} |")
    errs = [f for f in findings if f.severity == "error"]
    warns = [f for f in findings if f.severity == "warning"]
    infos = [f for f in findings if f.severity == "info"]
    lines.append(f"\n**Validation:** {len(errs)} errors · {len(warns)} warnings · {len(infos)} unverified claims\n")
    for title, group in (("Errors", errs), ("Warnings", warns)):
        if group:
            lines.append(f"<details><summary>{title} ({len(group)})</summary>\n")
            lines += [f"- `{f.code}` {f.message}" + (f" — `{f.file}`" if f.file else "") for f in group]
            lines.append("\n</details>\n")
    return "\n".join(x for x in lines if x is not None) + "\n"


CONCL = {"effective": "✅ effective", "not_effective": "❌ not effective", "not_applicable": "— n/a",
         "not_started": "⬜ not started"}


def internal_audit(model: Engagement, out: Path) -> list[tuple[str, str, str]]:
    """internal-audit.md (programme) + audit-<ID>.md (one report per audit). Returns index rows."""
    from .audit import audit_status, in_scope
    if not model.audits:
        return []
    rows = []
    prog = [f"# {model.client} — internal audit programme (9.2)\n", GEN]
    prog_rows = []
    for a in model.audits:
        st = audit_status(model, a["id"])
        c = st["conclusions"]
        prog_rows.append([f"[{a['id']}](audit-{a['id']}.md)", a["title"], a["status"],
                          f"{a['planned']['start']} → {a['planned']['end']}", ", ".join(a.get("auditors", [])),
                          f"{st['workpapers']} ({c.get('effective', 0)}✅ {c.get('not_effective', 0)}❌ {c.get('not_started', 0)}⬜)",
                          f"{st['findings']['major']} major · {st['findings']['minor']} minor · {st['findings']['ofi']} OFI"])
        audit_report(model, a, out)
    prog.append(_table(["Audit", "Title", "Status", "Planned", "Auditors", "Workpapers", "Findings"], prog_rows))
    (out / "internal-audit.md").write_text("".join(prog), encoding="utf-8")
    rows.append(("Internal audit", "internal-audit.md", "Audit programme, per-audit reports and workpaper results (9.2)"))
    return rows


def audit_report(model: Engagement, a: dict, out: Path) -> None:
    from .audit import audit_status, in_scope
    aid = a["id"]
    st = audit_status(model, aid)
    wps = model.workpapers.get(aid, {})
    rep = a.get("report") or {}
    L = [f"# Internal audit report — {aid}\n", GEN,
         f"**{a['title']}** · status **{a['status']}** · {model.client}\n\n",
         _table(["Item", "Detail"], [
             ["Scope", "all applicable requirements" if a.get("scope") == "all" else ", ".join(a.get("scope", []))],
             ["Excluded", ", ".join(a.get("exclude", []) or []) or "—"],
             ["Requirements in scope", len(in_scope(model, a))],
             ["Criteria", "; ".join(a.get("criteria", []) or ["ISO/IEC 42001:2023"])],
             ["Auditors", ", ".join(a.get("auditors", [])) + (f" (lead: {a['lead_auditor']})" if a.get("lead_auditor") else "")],
             ["Planned", f"{a['planned']['start']} → {a['planned']['end']}"],
             ["Report", f"issued {rep['issued']}, approved by {rep.get('approved_by', '?')}" if rep.get("issued") else "not issued"],
         ]), "\n"]
    if rep.get("conclusion"):
        L.append(f"## Conclusion\n\n{rep['conclusion']}\n\n")
    c = st["conclusions"]
    L.append(f"## Results\n\n{st['workpapers']} workpapers: {c.get('effective', 0)} effective, "
             f"{c.get('not_effective', 0)} not effective, {c.get('not_applicable', 0)} n/a, {c.get('not_started', 0)} not started; "
             f"{st['reviewed']} reviewed. Findings: {st['findings']['major']} major, {st['findings']['minor']} minor, "
             f"{st['findings']['ofi']} OFI ({st['open_findings']} open).\n\n")
    wrows = []
    for wid, wp in sorted(wps.items()):
        sample = wp.get("sample") or []
        exc = sum(1 for s in sample if s.get("result") == "exception")
        samp = f"{len(sample)} of {wp.get('sampling', {}).get('population_size', '?')}" + (f" · {exc} exc." if exc else "") if sample else "—"
        wrows.append([wid, wp.get("requirement"), wp.get("title", ""), samp, CONCL.get(wp.get("conclusion"), wp.get("conclusion")),
                      ", ".join(wp.get("findings") or []), wp.get("performed_by", ""), wp.get("reviewed_by", "")])
    L.append(_table(["WP", "Req.", "Title", "Sample", "Conclusion", "Findings", "Performed", "Reviewed"], wrows))
    fs = [f for f in model.findings if f.get("audit") == aid]
    if fs:
        L.append("\n## Findings\n\n")
        for f in fs:
            L.append(f"### {f['id']} — {f['grade']} — {f['requirement']}\n\n{f['description']}\n\n"
                     f"Status **{f['status']}** · owner {f.get('owner', '—')} · due {f.get('due', '—')}\n\n")
    (out / f"audit-{aid}.md").write_text("".join(L), encoding="utf-8")


def corrective_actions(model: Engagement, out: Path) -> list[tuple[str, str, str]]:
    if not model.findings:
        return []
    headers = ["ID", "Grade", "Req.", "Source", "Description", "Owner", "Due", "Status", "Root cause", "Corrective action", "Effective?"]
    rows = []
    for f in model.findings:
        eff = f.get("effectiveness") or {}
        rows.append([f["id"], f["grade"], f["requirement"], f["source"] + (f" {f['audit']}" if f.get("audit") else ""),
                     f["description"], f.get("owner", ""), f.get("due", ""), f["status"], f.get("root_cause", ""),
                     f.get("corrective_action", ""),
                     ("yes" if eff.get("effective") else "no") + f" ({eff.get('reviewed_on')})" if eff else ""])
    md = [f"# {model.client} — nonconformities & corrective actions (10.2)\n", GEN, _table(headers, rows)]
    (out / "corrective-actions.md").write_text("".join(md), encoding="utf-8")
    _write_csv(out / "corrective-actions.csv", headers, rows)
    return [("Corrective actions", "corrective-actions.md", "Nonconformities, OFIs and corrective actions (10.2) ([CSV](corrective-actions.csv))")]


def brief(model: Engagement, out: Path) -> None:
    """The analyst brief as Markdown, so it can be read directly on GitHub."""
    e, pb = model.engagement, model.playbook
    f = model.fmt
    m = metrics(model)
    L = [f"# {model.client} {pb.get('title_suffix', 'Project Brief')}\n", GEN,
         f"**{e.get('subtitle', 'Analyst Orientation')}**\n",
         f"> **TLDR:** {f(e.get('tldr') or pb.get('tldr_template', ''))}\n",
         "## 1. Client Overview\n", *[f"- {f(x)}" for x in e['client'].get('overview', [])], "",
         "## 2. AI Usage\n", *[f"- {f(x)}" for x in e.get('ai_usage', [])], "",
         "## 3. What is already in place\n",
         _table(["Foundation", "Examples"], [[x["foundation"], f(x["examples"])] for x in e.get("in_place", [])]),
         "## 4. Gap Analysis\n", f"> {f(pb.get('gap_callout', ''))}\n",
         _table(["Area", "What to verify / close"],
                [[g["area"], f(g["finding"])] for g in model.gaps
                 if g.get("in_brief", True) and g.get("status") in ("open", "in_progress")]),
         "### Analyst evidence test\n", *[f"- **{t['label']}** — {f(t['question'])}" for t in pb["evidence_test"]], "",
         f"### Readiness snapshot (as of {m['as_of']})\n",
         f"{m['requirements_ready']} of {m['requirements_applicable']} applicable requirements pass all four tests; "
         f"{m['gaps_open']} gaps open; {m['legs_verified_pct']}% of evidence-test legs verified.\n",
         _table(["Test", "Verified", "Partial", "Claimed", "Not started"],
                [[t["label"], *(m["legs"][t["key"]][s] for s in ("verified", "partial", "claimed", "not_started"))]
                 for t in pb["evidence_test"]]),
         "## 5. Timeline\n",
         _table(["Month", "Objective", "Deliverables"],
                [[ph["label"], ph["objective"], "<br>".join(f"• {f(d)}" for d in ph["deliverables"])] for ph in model.phases]),
         "## 6. Needs\n", *[f"- {f(x)}" for x in model.setting("needs", [])], "",
         "### Working rule\n", f"> {f(model.setting('working_rule', ''))}\n",
         f"## 7. {pb.get('requirements_heading', 'ISO Requirements')}\n", *[f"- {f(x)}" for x in pb.get("readiness_criteria", [])], "",
         "## 8. Engagement Guardrails\n"]
    b = e["budget"]
    L.append(f"- {b['hours_total']:g} total consulting hours" + (f": {b['note']}" if b.get("note") else "."))
    L += [f"- {f(x)}" for x in model.setting("guardrails", pb.get("default_guardrails", []))]
    L += ["", "## 9. Key Risks\n", *[f"- {f(x)}" for x in model.setting("key_risks", pb.get("default_risks", []))], ""]
    (out / "brief.md").write_text("\n".join(L), encoding="utf-8")


def index(model: Engagement, findings: list[Finding], out: Path, brief_docx: str | None,
          extra_rows: list[tuple[str, str, str]] | None = None) -> None:
    """Landing page for the published reports."""
    m = metrics(model)
    fw = model.catalog["framework"]["short_name"]
    rows = [
        ("Analyst brief", "brief.md", "The 9-section orientation brief" +
         (f" · [download Word]({brief_docx}?raw=1)" if brief_docx else "")),
        ("Control matrix", "control-matrix.md", "Every requirement with the four-part evidence test ([CSV](control-matrix.csv))"),
        ("Statement of Applicability", "soa.md", "Annex A applicability, justification and status ([CSV](soa.csv))"),
        ("Gap register", "gap-register.md", "Open and closed gaps with owners and due dates ([CSV](gap-register.csv))"),
        ("Evidence index", "evidence-index.md", "Requirement → evidence traceability ([CSV](evidence-index.csv))"),
    ] + list(extra_rows or [])
    banner = ("> ⚠️ **SANDBOX ENGAGEMENT.** Drata, cloud and AI-drafted content is simulated test data. "
              "Do not treat these reports as real client evidence.\n\n") if (model.engagement.get("sandbox") or {}).get("enabled") else ""
    L = [f"# {model.client} — {fw} readiness reports\n", banner,
         "<!-- Published automatically from the main branch. Do not edit this branch. -->\n",
         f"**As of {m['as_of']}.** Rebuilt automatically after every change to `main` and once a day. "
         "Use the branch history to see any earlier day; for a frozen copy to share with an auditor, publish a Release.\n",
         "| Report | What it shows |", "|---|---|"]
    L += [f"| [{name}]({link}) | {desc} |" for name, link, desc in rows]
    summary = summary_markdown(model, findings, m).split("\n", 1)[1]  # drop its title line
    L += ["", "## Readiness summary\n", summary]
    (out / "README.md").write_text("\n".join(L), encoding="utf-8")


def render_all(model: Engagement, findings: list[Finding], out: Path, brief_docx: str | None = None) -> str:
    out.mkdir(parents=True, exist_ok=True)
    control_matrix(model, out)
    soa(model, out)
    gap_register(model, out)
    evidence_index(model, out)
    brief(model, out)
    extra = internal_audit(model, out) + corrective_actions(model, out)
    index(model, findings, out, brief_docx, extra)
    return status(model, findings, out)
