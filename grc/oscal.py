"""OSCAL (NIST's Open Security Controls Assessment Language), JSON, version 1.2.3.

Export: the engagement record as OSCAL documents, each validated against NIST's schema before it is written.

    catalog.json            the framework's requirements as an OSCAL catalog (not written for TX-RAMP, whose
                            controls are NIST SP 800-53's: its profile points at NIST's published catalog)
    profile.json            the requirements in this record's scope
    ssp.json                system security plan: scope, owners, and each requirement's implementation and status
    assessment-plan.json    the plan the results refer to
    assessment-results.json the readiness result: an observation per evidence item, a finding per requirement
    poam.json               plan of action and milestones: one item per open gap, with its owner and due date

Import: an OSCAL catalog (optionally narrowed by a profile) as an engine framework catalog, so a client can run a
record against, for example, a FedRAMP Rev5 baseline or NIST SP 800-171 straight from the published OSCAL.

The results are a readiness assessment by the engagement team, not an independent assessment, and say so.
UUIDs are derived from the record (uuid5), so exporting twice gives the same document and diffs stay readable.
"""
from __future__ import annotations

import datetime as dt
import json
import re
import uuid
from functools import lru_cache
from pathlib import Path

from .model import ENGINE, LEGS, Engagement

OSCAL_VERSION = "1.2.3"
NS = uuid.UUID("6b1e2a3c-4d5f-5a6b-8c7d-9e0f1a2b3c4d")
NIST_CATALOG = ("https://raw.githubusercontent.com/usnistgov/oscal-content/v1.6.0/nist.gov/SP800-53/rev5/json/"
                "NIST_SP-800-53_rev5_catalog.json")
NIST_FRAMEWORKS = {"txramp"}           # requirement ids are NIST SP 800-53 control ids
STATE = {"Ready": "implemented", "In progress": "partial", "Unverified claim": "planned",
         "Not started": "planned", "Missing": "planned", "Excluded": "not-applicable"}


class OscalError(ValueError):
    pass


# requirements whose record has a validation error, for the export in progress (keyed by id(model)): they are
# never shown as implemented or satisfied, whatever their legs say
_FLAGGED: dict[int, set[str]] = {}


def _state(model: Engagement, rid: str) -> str:
    from .rules import requirement_state
    state = requirement_state(model, rid)
    if state == "Ready" and rid in _FLAGGED.get(id(model), set()):
        return "In progress"
    return state


# ------------------------------------------------------------------ ids, uuids, times
def control_id(framework: str, rid: str) -> str:
    """An OSCAL control id (a token: a letter first; letters, digits, '.', '-', '_'). NIST ids take NIST's form
    (AC-2(3) -> ac-2.3); others are prefixed with the framework (A.5.15 -> iso27001-A.5.15,
    164.308(a)(1)(ii)(A) -> hipaa-164.308.a.1.ii.A)."""
    rid = str(rid).strip()
    if framework in NIST_FRAMEWORKS:
        m = re.fullmatch(r"([A-Za-z]{2})-(\d+)(?:\((\d+)\))?", rid)
        if m:
            return f"{m.group(1).lower()}-{int(m.group(2))}" + (f".{int(m.group(3))}" if m.group(3) else "")
    if framework == "fedramp20x":
        return rid.lower()
    tok = re.sub(r"\(([^)]*)\)", r".\1", rid)
    tok = re.sub(r"[^A-Za-z0-9._-]+", "-", tok).strip("-.")
    return f"{framework}-{tok}"


def _cid(model: Engagement, rid: str) -> str:
    """The OSCAL id for a requirement: the id it came with when its catalog was imported from OSCAL, else
    `control_id`."""
    r = model.requirement_index.get(str(rid)) or {}
    return str(r.get("oscal_id") or control_id(model.catalog["framework"]["id"], rid))


def _uuid(*parts) -> str:
    return str(uuid.uuid5(NS, "/".join(str(p) for p in parts)))


def _when(d) -> str:
    """An OSCAL date-time (timezone required) from a date, a date-time or a string."""
    if isinstance(d, dt.datetime):
        return (d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)).isoformat()
    if isinstance(d, dt.date):
        return f"{d.isoformat()}T00:00:00Z"
    s = str(d or "").strip()
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
        return f"{s}T00:00:00Z"
    return s


def _text(s, fallback: str = "Not yet described.") -> str:
    s = " ".join(str(s or "").split())
    return s or fallback


def _metadata(model: Engagement, title: str, today: dt.date) -> dict:
    from . import __version__
    party = _uuid(model.client, "party")
    return {"title": title, "last-modified": _when(today), "version": f"{today.isoformat()}",
            "oscal-version": OSCAL_VERSION,
            "props": [{"name": "keywords", "value": f"{model.catalog['framework']['short_name']}, readiness"}],
            "parties": [{"uuid": party, "type": "organization", "name": model.client}],
            "remarks": f"Generated by the GRC readiness engine {__version__} from the engagement record."}


# ------------------------------------------------------------------ schema validation
@lru_cache(maxsize=1)
def _validator():
    import jsonschema
    raw = (ENGINE / "oscal" / "oscal_complete_schema.json").read_text(encoding="utf-8")
    # NIST's token pattern uses \p{L} and \p{N}, which Python's re lacks: same classes, Python spelling.
    raw = raw.replace(r"^(\\p{L}|_)(\\p{L}|\\p{N}|[.\\-_])*$", r"^([^\\W\\d_]|_)([^\\W\\d_]|\\d|[.\\-_])*$")
    return jsonschema.Draft7Validator(json.loads(raw))


def validate(doc: dict) -> list[str]:
    """Schema problems in an OSCAL document, as 'path: message' lines (empty when valid)."""
    out = []
    for e in sorted(_validator().iter_errors(doc), key=lambda e: list(e.absolute_path)):
        where = "/".join(str(p) for p in e.absolute_path) or "(root)"
        out.append(f"{where}: {e.message[:300]}")
    return out


# ------------------------------------------------------------------ export
def _in_scope(model: Engagement) -> list[dict]:
    return [r for r in model.requirements if model.in_category_scope(str(r["id"]))]


def catalog_doc(model: Engagement, today: dt.date) -> dict:
    fw = model.catalog["framework"]
    groups = {str(g["id"]): g for g in model.catalog.get("groups") or [] if isinstance(g, dict)}
    by_group: dict[str, list] = {}
    for r in model.requirements:
        rid = str(r["id"])
        cid = _cid(model, rid)
        control = {"id": cid, "title": _text(r.get("title"), rid),
                   "props": [{"name": "label", "value": rid}] + (
                       [{"name": "sort-id", "value": cid}]),
                   "parts": [{"id": f"{cid}_smt", "name": "statement", "prose": _text(r.get("intent"), "See the source.")}]}
        if r.get("category"):
            control["props"].append({"name": "category", "ns": "https://github.com/Baderholdjr/grc-readiness/ns/oscal", "value": str(r["category"])})
        by_group.setdefault(str(r.get("group") or ""), []).append(control)
    meta = _metadata(model, f"{fw['name']} (as used by the GRC readiness engine)", today)
    meta["version"] = str(fw.get("version") or today.isoformat())
    meta["remarks"] = ("Requirement titles and statements as held in the engine's catalog. For licensed standards "
                       "(ISO/IEC, AICPA) these are paraphrases; the published standard is the authority.")
    doc = {"uuid": _uuid(fw["id"], "catalog"), "metadata": meta}
    grouped = [g for g in by_group if g]
    if grouped:
        doc["groups"] = [{"id": control_id(fw["id"], f"group-{g}"), "title": _text((groups.get(g) or {}).get("title"), g),
                          "controls": by_group[g]} for g in grouped]
    if by_group.get(""):
        doc["controls"] = by_group[""]
    return {"catalog": doc}


def profile_doc(model: Engagement, today: dt.date) -> dict:
    fw = model.catalog["framework"]
    ids = [_cid(model, str(r["id"])) for r in _in_scope(model)]
    href = NIST_CATALOG if fw["id"] in NIST_FRAMEWORKS else "catalog.json"
    meta = _metadata(model, f"{model.client}: {fw['short_name']} requirements in scope", today)
    return {"profile": {"uuid": _uuid(model.client, fw["id"], "profile"), "metadata": meta,
                        "imports": [{"href": href, "include-controls": [{"with-ids": ids}]}],
                        "merge": {"as-is": True}}}


def _component(model: Engagement) -> str:
    return _uuid(model.client, model.catalog["framework"]["id"], "this-system")


def ssp_doc(model: Engagement, today: dt.date) -> dict:
    fw = model.catalog["framework"]
    scope = model.engagement.get("scope") or {}
    statement = _text(model.fmt(str(scope.get("statement") or "")), f"The {model.system_abbrev} in scope.")
    comp = _component(model)
    owners = sorted({str((model.controls.get(str(r["id"])) or {}).get("owner") or "") for r in _in_scope(model)} - {""})
    roles = [{"id": "control-owner", "title": "Control owner"}]
    users = [{"uuid": _uuid(model.client, "user", o), "title": o, "role-ids": ["control-owner"]} for o in owners] or \
            [{"uuid": _uuid(model.client, "user", "owners"), "title": "Control owners (not yet assigned)"}]
    reqs = []
    for r in _in_scope(model):
        rid = str(r["id"])
        c = model.controls.get(rid) or {}
        state = _state(model, rid)
        status = {"state": STATE.get(state, "planned")}
        if state == "Excluded":
            status["remarks"] = _text(c.get("justification"), "Excluded; no justification recorded.")
        elif state == "Unverified claim":
            status["remarks"] = "The client says this is in place; not yet verified against evidence."
        elif state == "In progress":
            status["remarks"] = "Readiness state: In progress." + (
                " The record has a validation error on this requirement." if rid in _FLAGGED.get(id(model), set()) else "")
        desc = c.get("implementation") or c.get("description") or c.get("notes")
        item = {"uuid": _uuid(model.client, fw["id"], "req", rid), "control-id": _cid(model, rid),
                "props": [{"name": "label", "value": rid}],
                "by-components": [{"component-uuid": comp, "uuid": _uuid(model.client, fw["id"], "byc", rid),
                                   "description": _text(model.fmt(str(desc or ""))),
                                   "implementation-status": status}]}
        if c.get("owner"):
            item["responsible-roles"] = [{"role-id": "control-owner",
                                          "party-uuids": [_uuid(model.client, "party")]}]
            item["remarks"] = f"Owner: {c['owner']}"
        reqs.append(item)
    meta = _metadata(model, f"{model.client}: {fw['short_name']} System Security Plan", today)
    meta["roles"] = roles
    info_type = {"uuid": _uuid(model.client, "info-type"), "title": "Information in scope",
                 "description": "The information the system in scope stores, processes or transmits, as described in the "
                                "engagement's scope and inventory.",
                 "confidentiality-impact": {"base": "fips-199-moderate"},
                 "integrity-impact": {"base": "fips-199-moderate"},
                 "availability-impact": {"base": "fips-199-moderate"}}
    doc = {"uuid": _uuid(model.client, fw["id"], "ssp"), "metadata": meta,
           "import-profile": {"href": "profile.json"},
           "system-characteristics": {
               "system-ids": [{"identifier-type": "https://ietf.org/rfc/rfc4122", "id": comp}],
               "system-name": f"{model.client} — {fw['short_name']} scope",
               "description": statement,
               "system-information": {"information-types": [info_type]},
               "status": {"state": "under-development",
                          "remarks": "Readiness engagement in progress; categorization to be confirmed by the system owner."},
               "authorization-boundary": {"description": statement}},
           "system-implementation": {
               "users": users,
               "components": [{"uuid": comp, "type": "this-system", "title": f"{model.client} {model.system_abbrev}",
                               "description": statement, "status": {"state": "under-development"}}]},
           "control-implementation": {
               "description": f"How {model.client} meets each {fw['short_name']} requirement in scope, from the "
                              "engagement record. Implementation status reflects the four-part evidence test.",
               "implemented-requirements": reqs}}
    inv = [i for i in model.inventory if isinstance(i, dict) and i.get("name")]
    if inv:
        doc["system-implementation"]["inventory-items"] = [
            {"uuid": _uuid(model.client, "inv", n, i.get("id") or i["name"]), "description": _text(i.get("name")),
             "props": [{"name": "asset-type", "value": _token_value(i.get("kind") or "other")}]}
            for n, i in enumerate(inv)]
    return {"system-security-plan": doc}


def _token_value(v) -> str:
    v = re.sub(r"[^A-Za-z0-9._-]+", "-", str(v)).strip("-.")
    return v or "other"


def assessment_plan_doc(model: Engagement, today: dt.date) -> dict:
    meta = _metadata(model, f"{model.client}: {model.catalog['framework']['short_name']} readiness assessment plan", today)
    return {"assessment-plan": {
        "uuid": _uuid(model.client, model.catalog["framework"]["id"], "ap"), "metadata": meta,
        "import-ssp": {"href": "ssp.json"},
        "reviewed-controls": {"description": "Every requirement in the profile, tested with the four-part evidence "
                                             "test: documented, implemented, evidence exists, tested.",
                              "control-selections": [{"include-all": {}}]}}}


def _evidence_method(ev: dict) -> str:
    return {"test": "TEST", "sample": "TEST", "interview": "INTERVIEW"}.get(str(ev.get("type") or ""), "EXAMINE")


def assessment_results_doc(model: Engagement, today: dt.date) -> dict:
    fw = model.catalog["framework"]
    idx = model.evidence_index
    observations, obs_of = [], {}
    for r in _in_scope(model):
        c = model.controls.get(str(r["id"])) or {}
        for leg in LEGS:
            for eid in (c.get("test") or {}).get(leg, {}).get("evidence") or []:
                eid = str(eid)
                if eid in obs_of or eid not in idx:
                    continue
                ev = idx[eid]
                o = {"uuid": _uuid(model.client, "obs", eid), "title": _text(ev.get("title"), eid),
                     "description": f"Evidence {eid} ({ev.get('type') or 'record'}), held at its source; "
                                    "this record points to it.",
                     "props": [{"name": "label", "value": eid}],
                     "methods": [_evidence_method(ev)],
                     "collected": _when(ev.get("collected") or today)}
                if not ev.get("collected"):    # OSCAL requires a date: say this one is the export's, not the record's
                    o["remarks"] = "No collection date in the evidence index; the export date is shown."
                exp = model.evidence_expiry(ev) if hasattr(model, "evidence_expiry") else None
                if exp:
                    o["expires"] = _when(exp)
                if ev.get("location"):
                    o["relevant-evidence"] = [{"description": f"Location: {ev['location']}"}]
                obs_of[eid] = o["uuid"]
                observations.append(o)
    findings = []
    for r in _in_scope(model):
        rid = str(r["id"])
        c = model.controls.get(rid) or {}
        state = _state(model, rid)
        if state == "Excluded":
            continue
        legs = {k: str(((c.get("test") or {}).get(k) or {}).get("status") or "not_started") for k in LEGS}
        f = {"uuid": _uuid(model.client, fw["id"], "finding", rid), "title": f"{rid}: {_text(r.get('title'), rid)}",
             "description": f"Readiness state: {state}. " + "; ".join(f"{k} {v.replace('_', ' ')}" for k, v in legs.items()) + ".",
             "target": {"type": "statement-id", "target-id": f"{_cid(model, rid)}_smt",
                        "status": {"state": "satisfied" if state == "Ready" else "not-satisfied"}}}
        rel = sorted({obs_of[str(e)] for k in LEGS for e in ((c.get("test") or {}).get(k) or {}).get("evidence") or []
                      if str(e) in obs_of})
        if rel:
            f["related-observations"] = [{"observation-uuid": u} for u in rel]
        findings.append(f)
    start = (model.engagement.get("dates") or {}).get("start") or today
    result = {"uuid": _uuid(model.client, fw["id"], "result", today.isoformat()),
              "title": f"{fw['short_name']} readiness result, {today.isoformat()}",
              "description": "A readiness assessment by the engagement team using the four-part evidence test. It is "
                             "not an independent assessment or a certification decision.",
              "start": _when(start), "end": _when(today),
              "reviewed-controls": {"control-selections": [{"include-all": {}}]}}
    if observations:
        result["observations"] = observations
    if findings:
        result["findings"] = findings
    meta = _metadata(model, f"{model.client}: {fw['short_name']} readiness assessment results", today)
    return {"assessment-results": {"uuid": _uuid(model.client, fw["id"], "ar"), "metadata": meta,
                                   "import-ap": {"href": "assessment-plan.json"}, "results": [result]}}


def poam_doc(model: Engagement, today: dt.date) -> dict:
    fw = model.catalog["framework"]
    risks, items = [], []
    for g in model.gaps:
        if not isinstance(g, dict) or g.get("status") not in ("open", "in_progress") or not model.gap_in_scope(g):
            continue
        gid = str(g.get("id"))
        risk = {"uuid": _uuid(model.client, "risk", gid), "title": _text(g.get("area"), gid),
                "description": _text(model.fmt(str(g.get("finding") or ""))),
                "statement": f"Until {gid} is closed, the requirements it names are not met: "
                             f"{', '.join(str(x) for x in g.get('requirements') or []) or 'none named'}.",
                "status": "open",
                "props": [{"name": "label", "value": gid},
                          {"name": "priority", "ns": "https://github.com/Baderholdjr/grc-readiness/ns/oscal", "value": str(g.get("severity") or "medium")}]}
        if g.get("due"):
            risk["deadline"] = _when(g["due"])
        risks.append(risk)
        item = {"uuid": _uuid(model.client, "poam", gid), "title": f"{gid}: {_text(g.get('area'), gid)}",
                "description": _text(model.fmt(str(g.get("finding") or ""))),
                "props": [{"name": "label", "value": gid}],
                "related-risks": [{"risk-uuid": risk["uuid"]}]}
        notes = [f"Owner: {g['owner']}" if g.get("owner") else "Owner: not yet assigned"]
        if g.get("phase"):
            notes.append(f"Phase: {g['phase']}")
        item["remarks"] = ". ".join(notes) + "."
        items.append(item)
    meta = _metadata(model, f"{model.client}: {fw['short_name']} plan of action and milestones", today)
    doc = {"uuid": _uuid(model.client, fw["id"], "poam"), "metadata": meta, "import-ssp": {"href": "ssp.json"},
           "system-id": {"identifier-type": "https://ietf.org/rfc/rfc4122", "id": _component(model)},
           "poam-items": items}
    if risks:
        doc["risks"] = risks
    if not items:     # the schema needs at least one item: say there is nothing open
        doc["poam-items"] = [{"uuid": _uuid(model.client, "poam", "none"), "title": "No open gaps",
                              "description": "The gap register has no open or in-progress gap in scope."}]
    return {"plan-of-action-and-milestones": doc}


def export(model: Engagement, out: Path, today: dt.date | None = None, force: bool = False) -> list[tuple[str, int]]:
    """Write the OSCAL documents to out/. Refuses (OscalError) when the record has validation errors (unless
    `force`: a draft, in which no requirement with an error shows as implemented or satisfied) or when any
    document fails NIST's schema."""
    from .rules import validate as validate_record
    today = today or model.today
    errors = [f for f in validate_record(model) if f.severity == "error"]
    if errors and not force:
        raise OscalError(f"the record has {len(errors)} validation error(s) (run validate); fix them, or use --force "
                         "for a draft export in which no requirement with an error is shown as met")
    _FLAGGED[id(model)] = {str(f.ref) for f in errors if f.ref}
    try:
        docs = {"profile.json": profile_doc(model, today), "ssp.json": ssp_doc(model, today),
                "assessment-plan.json": assessment_plan_doc(model, today),
                "assessment-results.json": assessment_results_doc(model, today), "poam.json": poam_doc(model, today)}
        if model.catalog["framework"]["id"] not in NIST_FRAMEWORKS:
            docs = {"catalog.json": catalog_doc(model, today), **docs}
    finally:
        _FLAGGED.pop(id(model), None)
    if errors:
        for d in docs.values():
            meta = d[next(iter(d))]["metadata"]
            meta["remarks"] = (f"DRAFT: exported with {len(errors)} validation error(s) in the record. "
                               + meta["remarks"])
    problems = {name: validate(d) for name, d in docs.items()}
    bad = {k: v for k, v in problems.items() if v}
    if bad:
        lines = [f"{k}: {p}" for k, v in bad.items() for p in v[:5]]
        raise OscalError("OSCAL schema check failed:\n  " + "\n  ".join(lines))
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, d in docs.items():
        (out / name).write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        written.append((name, (out / name).stat().st_size))
    return written


# ------------------------------------------------------------------ import
def _prose(parts) -> str:
    out = []
    for p in parts or []:
        if p.get("name") in ("statement", "item"):
            lab = next((str(x.get("value")) for x in p.get("props") or [] if x.get("name") == "label"), "")
            if p.get("prose"):
                out.append(f"{lab} {p['prose']}".strip() if p.get("name") == "item" else p["prose"])
            elif lab and p.get("name") == "item":
                out.append(lab)
            out.append(_prose(p.get("parts")))
    return " ".join(x for x in out if x)


def _label(ctrl: dict) -> str:
    for p in ctrl.get("props") or []:
        if p.get("name") == "label" and p.get("class") not in ("zero-padded",):
            return str(p.get("value"))
    return str(ctrl["id"])


def _walk(container: dict, group: str | None = None, groups: dict | None = None, trail: str = "",
          parent_title: str = ""):
    """(control, group id) for every control, depth first, in catalog order. Groups may nest and their ids are
    optional in OSCAL: a nested group is recorded (in `groups`) as one flat group titled 'Parent: Child', and a
    group without an id gets one from its position."""
    groups = {} if groups is None else groups
    for c in container.get("controls") or []:
        yield c, group
        yield from _walk({"controls": c.get("controls")}, group, groups, trail, parent_title)
    for n, g in enumerate(container.get("groups") or [], 1):
        gid = str(g.get("id") or f"group{trail}-{n}")
        title = str(g.get("title") or gid)
        groups.setdefault(gid, f"{parent_title}: {title}" if parent_title else title)
        yield from _walk(g, gid, groups, f"{trail}-{n}", groups[gid])


def _walk_controls(container: dict):
    yield from _walk(container)


def _all_params(cat: dict) -> dict:
    params = {p["id"]: p for p in cat.get("params") or []}
    stack = list(cat.get("groups") or []) + list(cat.get("controls") or [])
    while stack:
        x = stack.pop()
        params.update({p["id"]: p for p in x.get("params") or []})
        stack += list(x.get("groups") or []) + list(x.get("controls") or [])
    return params


def _params_text(text: str, params: dict) -> str:
    """{{ insert: param, ac-01_odp.01 }} -> its label, or its choices, so statements read in English."""
    def sub(m):
        p = params.get(m.group(1)) or {}
        sel = p.get("select") or {}
        if sel.get("choice"):
            how = "one or more of" if sel.get("how-many") == "one-or-more" else "one of"
            choices = "; ".join(" ".join(_params_text(str(ch), params).split()) for ch in sel["choice"])
            return f"[selection ({how}): {choices}]"
        return f"[{p.get('label') or 'organization-defined value'}]"
    return re.sub(r"\{\{\s*insert:\s*param,\s*([^\s}]+)\s*\}\}", sub, text)


def _load(path: Path, model_name: str) -> dict:
    from .safety import check_file
    check_file(Path(path), max_bytes=80 * 1024 * 1024)
    try:
        d = json.loads(Path(path).read_text(encoding="utf-8"))
        if not isinstance(d, dict) or model_name not in d:
            raise OscalError(f"{path}: not an OSCAL {model_name} (no '{model_name}' at the top)")
        errs = validate(d)
    except RecursionError:
        raise OscalError(f"{path}: nested too deeply to be an OSCAL file") from None
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise OscalError(f"{path}: not JSON ({exc})") from None
    if errs:
        raise OscalError(f"{path}: not valid OSCAL:\n  " + "\n  ".join(errs[:8]))
    return d[model_name]


def _matches(cid: str, pattern: str) -> bool:
    import fnmatch
    return fnmatch.fnmatchcase(cid, pattern)


def _select(profile: dict, cat: dict) -> set[str]:
    """The control ids a profile chooses from one catalog: include-all or include-controls (with-ids, matching,
    with-child-controls), minus exclude-controls. Profiles that import other profiles, or tailor parameters and
    parts (set-parameters, alter), are refused: import their resolved catalog instead."""
    if any(k in (profile.get("modify") or {}) for k in ("set-parameters", "alters")):
        raise OscalError("the profile changes parameters or control text (modify); import the resolved catalog the "
                         "publisher provides instead, without --profile")
    imports = profile.get("imports") or []
    if len(imports) != 1:
        raise OscalError("the profile imports more than one source; import the resolved catalog instead, without --profile")
    imp = imports[0]
    if str(imp.get("href") or "").lower().find("profile") >= 0:
        raise OscalError("the profile imports another profile; import the resolved catalog instead, without --profile")
    tree = {c["id"]: c for c, _ in _walk_controls(cat)}
    children = {cid: [k["id"] for k, _ in _walk({"controls": c.get("controls")})] for cid, c in tree.items()}

    def pick(selectors) -> set[str]:
        got = set()
        for sel in selectors or []:
            ids = set(sel.get("with-ids") or [])
            missing = sorted(ids - set(tree))
            if missing:
                raise OscalError(f"the profile names {len(missing)} control(s) the catalog doesn't have "
                                 f"({', '.join(missing[:8])}): is this the catalog the profile imports?")
            for m in sel.get("matching") or []:
                ids |= {cid for cid in tree if _matches(cid, str(m.get("pattern") or ""))}
            if sel.get("with-child-controls") == "yes":
                ids |= {k for cid in list(ids) for k in children.get(cid, [])}
            got |= ids
        return got

    wanted = set(tree) if imp.get("include-all") is not None else pick(imp.get("include-controls"))
    return wanted - pick(imp.get("exclude-controls"))


def import_catalog(catalog_path: Path, profile_path: Path | None, fw_id: str, name: str,
                   short_name: str | None = None) -> dict:
    """An engine catalog (as a dict for catalog.yaml) from an OSCAL catalog, narrowed to what a profile selects
    when one is given. Both files are checked against NIST's schema first."""
    if not re.fullmatch(r"[a-z][a-z0-9_-]{1,40}", fw_id):
        raise OscalError("--id: lower-case letters, digits, '-' or '_', starting with a letter")
    cat = _load(catalog_path, "catalog")
    wanted = _select(_load(profile_path, "profile"), cat) if profile_path is not None else None
    params = _all_params(cat)
    groups: dict[str, str] = {}
    reqs, seen = [], set()
    for c, group in _walk(cat, None, groups):
        if wanted is not None and c["id"] not in wanted:
            continue
        if any(p.get("name") == "status" and str(p.get("value")).lower() in ("withdrawn", "moved")
               for p in c.get("props") or []):
            continue
        rid = _label(c)
        if rid in seen:
            rid = c["id"]
        seen.add(rid)
        intent = _params_text(_prose(c.get("parts")), params) or c.get("title") or rid
        reqs.append({"id": rid, "kind": "control", "category": "core", "group": group or "", "title": c.get("title") or rid,
                     "intent": " ".join(intent.split())[:4000], "evidence_examples": ["Policy or procedure", "Records showing it operates"],
                     "oscal_id": c["id"]})
    if not reqs:
        raise OscalError("no controls selected: check the profile's include-controls")
    used = {r["group"] for r in reqs}
    meta = cat.get("metadata") or {}
    return {"framework": {"id": fw_id, "name": name, "short_name": short_name or name,
                          "management_system": "Security program", "source": f"OSCAL catalog: {meta.get('title')}",
                          "version": str(meta.get("version") or "")},
            "kinds": {"control": {"label": "Control", "short": "Control", "mandatory": False}},
            "categories": [{"id": "core", "title": "Controls in the baseline", "short": "Baseline", "required": True}],
            "groups": [{"id": g, "title": t} for g, t in groups.items() if g in used],
            "requirements": reqs}


def write_framework(root: Path, catalog: dict, force: bool = False) -> list[Path]:
    """Write an imported catalog as frameworks/<id>/catalog.yaml in a client repository, with a starting
    playbook.yaml (kept if one is already there). Refuses to replace a built-in framework."""
    import yaml
    fw = catalog["framework"]
    if (ENGINE / "frameworks" / fw["id"]).exists():
        raise OscalError(f"'{fw['id']}' is a built-in framework; choose another --id")
    d = Path(root) / "frameworks" / fw["id"]
    cat_path, pb_path = d / "catalog.yaml", d / "playbook.yaml"
    if cat_path.exists() and not force:
        raise OscalError(f"{cat_path} exists; use --force to replace it (the playbook is kept)")
    d.mkdir(parents=True, exist_ok=True)
    head = (f"# {fw['name']}: imported from OSCAL by `grc oscal import` ({fw['source']}).\n"
            "# Re-run the import to refresh it. Requirement ids are the controls' labels; oscal_id keeps the OSCAL id.\n")
    cat_path.write_text(head + yaml.safe_dump(catalog, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    written = [cat_path]
    if not pb_path.exists():
        text = (ENGINE / "oscal" / "playbook.yaml").read_text(encoding="utf-8")
        pb_path.write_text(text.replace("{framework}", str(fw["short_name"])), encoding="utf-8")
        written.append(pb_path)
    return written
