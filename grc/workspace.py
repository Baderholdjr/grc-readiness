"""The consultant workspace (docs/WORKSPACE.md): one Cloudflare Worker for the practice's consultants, who sign in
with GitHub through the Yata Workspace GitHub App and propose changes to client records as pull requests in
their own name. `grc workspace --config workspace.yaml` builds the bundle; its workflow deploys it.

workspace.yaml (in the practice's own workspace repository; no secrets in it):

    github_client_id: Iv23li...      # the App's Client ID (not a secret)
    consultants: [Baderholdjr]       # GitHub logins allowed to sign in
    worker_name: yata-workspace    # optional
    base_branch: main                # optional

Secrets, set on the Worker (never in the repository): GITHUB_CLIENT_SECRET, SESSION_KEY.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

import yaml

from .model import ENGINE

SITE = ENGINE / "workspace"
LOGIN = re.compile(r"^[A-Za-z0-9-]{1,39}$")


class WorkspaceError(ValueError):
    pass


def load_config(path: Path) -> dict:
    from .model import load_yaml
    try:
        cfg = load_yaml(Path(path))
    except SystemExit as exc:
        raise WorkspaceError(str(exc)) from None
    except OSError as exc:
        raise WorkspaceError(f"{path}: {exc.strerror}") from None
    cid = str(cfg.get("github_client_id") or "")
    if not re.fullmatch(r"[A-Za-z0-9.]{8,40}", cid):
        raise WorkspaceError("github_client_id: the App's Client ID, from its settings page (it isn't a secret)")
    people = [str(x) for x in cfg.get("consultants") or []]
    if not people or not all(LOGIN.fullmatch(x) for x in people):
        raise WorkspaceError("consultants: a list of GitHub logins allowed to sign in")
    name = str(cfg.get("worker_name") or "yata-workspace")
    if not re.fullmatch(r"[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?", name):
        raise WorkspaceError("worker_name: lower-case letters, digits and hyphens")
    base = str(cfg.get("base_branch") or "main")
    if not re.fullmatch(r"[A-Za-z0-9._/-]{1,100}", base) or ".." in base:
        raise WorkspaceError("base_branch: a branch name")
    return {"github_client_id": cid, "consultants": people, "worker_name": name, "base_branch": base}


def build(cfg: dict, out: Path) -> list[str]:
    from .portal import _toml
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    pub = out / "public"
    pub.mkdir(parents=True)
    shutil.copyfile(SITE / "worker.js", out / "worker.js")
    shutil.copyfile(ENGINE / "portal" / "access.js", out / "access.js")
    shutil.copyfile(ENGINE / "portal" / "yamledit.js", out / "yamledit.js")
    shutil.copyfile(ENGINE / "portal" / "recordcheck.js", out / "recordcheck.js")
    shutil.copyfile(SITE / "vendor" / "js-yaml.mjs", out / "js-yaml.mjs")
    for f in (SITE / "site").iterdir():
        shutil.copyfile(f, pub / f.name)
    (out / "wrangler.toml").write_text("\n".join([
        "# Generated by `grc workspace`. Change workspace.yaml, not this file.",
        f"name = {_toml(cfg['worker_name'])}",
        'main = "worker.js"',
        'compatibility_date = "2025-06-01"',
        "workers_dev = true",
        "",
        "[observability]",
        "enabled = true               # Worker logs: sign-ins and changes, with the GitHub login",
        "",
        "[assets]",
        'directory = "public"',
        'binding = "ASSETS"',
        "run_worker_first = true",
        "",
        "[vars]",
        f"GITHUB_CLIENT_ID = {_toml(cfg['github_client_id'])}",
        f"CONSULTANTS = {_toml(','.join(cfg['consultants']))}",
        f"BASE_BRANCH = {_toml(cfg['base_branch'])}",
        "# Secrets (wrangler secret put, or the Cloudflare dashboard): GITHUB_CLIENT_SECRET, SESSION_KEY",
        "",
    ]), encoding="utf-8")
    return [f"workspace written to {out}/ (worker {cfg['worker_name']}) for {len(cfg['consultants'])} consultant(s)",
            "  set the Worker secrets GITHUB_CLIENT_SECRET and SESSION_KEY before it will sign anyone in"]
