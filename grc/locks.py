"""Paths of the engine's hash-locked dependency files, for workflows to install from:

    pip install --require-hashes -r "$(python -m grc.locks engine)"

engine      the engine's own dependencies
collectors  plus the cloud SDKs the evidence collectors use (boto3, google-auth)
dev         plus pytest
security    the scanners the Security workflow runs (bandit, pip-audit, zizmor)

The files are generated by pip-compile for Python 3.12 (the version the workflows use); the Security
workflow fails when one is out of date and prints the regenerated file. Imports nothing, so it runs before
the engine's dependencies are installed.
"""
import os
import sys

NAMES = ("engine", "collectors", "dev", "security")


def path(name: str) -> str:
    if name not in NAMES:
        raise SystemExit(f"unknown lock '{name}': one of {', '.join(NAMES)}")
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "resources", "locks", f"{name}.txt")


if __name__ == "__main__":
    print(path(sys.argv[1] if len(sys.argv) > 1 else "engine"))
